/* ════════════════════════════════════════════════════════════
 * «ПРЕСТОЛ» — СПРАЙТ. Процедурный ветхозаветный ангел.
 * ────────────────────────────────────────────────────────────
 * ПОЧЕМУ НЕ КАРТИНКА. Все корабли на доске — кэшированный офскрин: нарисовали
 * раз, дальше только вертим. Ангелу это не подходит по сути: у него нет позы.
 * Крылья бьют не в такт, кольца идут навстречу друг другу, глаза моргают
 * вразнобой и все вместе смотрят на того, кого он сейчас убивает. Любой
 * запечённый кадр это убивает — поэтому здесь всё считается каждый кадр.
 *
 * ЧТО ИМЕННО РИСУЕМ (и почему так, а не «ангелочек с крылышками»):
 *   • ОФАНИМ — колёса в колёсах, усеянные глазами. Два кольца в разных
 *     наклонах, идут навстречу: получается не вращение, а «глаз не выходит
 *     из тебя», сколько ни поворачивай.
 *   • СЕРАФИМ — шесть крыл тремя парами. Верхняя пара закрывает лик, нижняя
 *     закрывает ноги, средняя — та, которой летают. Они и бьют в разном такте.
 *   • НИМБ — не кружок над головой, а наклонный обод под углом к плоскости
 *     доски, с бегущим по нему блеском.
 *   • ЛИКА НЕТ. Внутри столб света и пустота. Это сознательно: как только у
 *     него появляется лицо, он перестаёт быть страшным и становится персонажем.
 *
 * ЦВЕТ. Тон стороны (свой/союзный/чужой) уходит ТОЛЬКО в дальнее свечение.
 * Само тело всегда кость и золото: ангел не принадлежит стороне, он ей
 * временно попутчик.
 *
 * ЖИВАЯ ПОЗА — ДА, ПОЛНАЯ ПОДРОБНОСТЬ — НЕ ВЕЗДЕ. Считать позу каждый кадр
 * дёшево: это десяток синусов. Дорого — СЛОИ, которые под эту позу рисуются.
 * Поэтому экономят не на движении, а на подробности: см. angelDetail и
 * opt.detail — вызывающий вправе поставить потолок ступени под свой экран.
 *
 * ДВА ВОПЛОЩЕНИЯ. Первое тело выбили 22.08; после восьми часов тишины встало
 * второе (см. _angel_phase2.sql) — то, которое ест миры и разворачивает снаряды
 * обратно. Это ОДИН спрайт с развилкой по opt.phase, а не второй файл: у них
 * общая анатомия (офаним, серафим, нимб, заслонка), различаются палитра, габарит
 * и то, что второе тело нарастило поверх — шипы ободьев, венец, доли плоти.
 * Держать их одним кодом обязательно: иначе первая же правка облика уходит в
 * одну фазу и молча расходится со второй.
 *
 * ЗАВИСИМОСТИ: ничего. Чистый canvas 2D, наружу:
 *   angelDraw(ctx, opt)    — нарисовать в точке (opt.detail — потолок ступени,
 *                            opt.phase 1|2 — воплощение, opt.mass 0..1 — плоть)
 *   angelWantsFrames()     — доске: держи rAF живым, пока он на поле
 *   angelHit(id)           — вспышка нимба на попадании (урона нет)
 * ════════════════════════════════════════════════════════════ */

