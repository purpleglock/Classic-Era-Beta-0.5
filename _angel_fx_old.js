ANGEL.gc = {}; ANGEL.gcN = 0;
function angelGrad(k, make) {
  var g = ANGEL.gc[k];
  if (g) return g;
  if (ANGEL.gcN > 400) { ANGEL.gc = {}; ANGEL.gcN = 0; }
  g = make(); ANGEL.gc[k] = g; ANGEL.gcN++;
  return g;
}
