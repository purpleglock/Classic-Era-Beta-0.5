-- Знает ли держава, с чем имеет дело.
create or replace function public._angel_knows(p_fid text)
returns boolean language sql stable security definer set search_path=public as $$
  select coalesce((select coalesce(research, '[]'::jsonb) ? 'pol.throne_codex'
                     from public.faction_economy where faction_id = p_fid), false)
$$;

-- ── 2. КОДЕКС: ЧТО ИМЕННО УЗНАЁТ ИССЛЕДОВАВШИЙ ──────────────
-- Без технологии — те же помехи, что и везде. С технологией — разбор по
-- пунктам, включая то, что бесполезно: знать, чего НЕ делать, тут дороже.
create or replace function public.angel_codex()
returns jsonb language plpgsql security definer set search_path=public as $$
declare me text; a record; knows boolean;
begin
  begin me := public._ec_my_fid_opt(); exception when others then me := null; end;
  select * into a from public.angel_state order by created_at limit 1;
  if a.faction_id is null then
    return jsonb_build_object('ok', true, 'exists', false);
  end if;

  knows := (me is not null and (public._angel_knows(me) or me = a.faction_id));
  if not knows then
    return jsonb_build_object('ok', true, 'exists', true, 'known', false,
      'tech', 'pol.throne_codex',
      'teaser', public._angel_glitch('Отметка не поддаётся классификации. Требуется разбор ', 0.30)
                || public._angel_scream(12),
      'lines', jsonb_build_array(
        public._angel_scream(22), public._angel_scream(17), public._angel_scream(25)));
  end if;

  return jsonb_build_object('ok', true, 'exists', true, 'known', true,
    'title', 'Престол: разбор отметки',
    'danger', jsonb_build_array(
      'В бою ему нельзя нанести урон. Совсем. Ни залпом, ни тараном, ни ядерной боеголовкой: он не теряет корпуса, не глохнет и не имеет перезарядок. Флот, встретивший его на доске, считается потерянным целиком.',
      'Он не даёт уйти в прыжок и видит сквозь маскировку. Разорвать контакт нельзя — можно только не входить в систему, где он стоит.',
      'Пока он висит над вашей системой, её достаток падает каждый час, а он тем же часом становится богаче. Осада без единого выстрела.'),
    'works', jsonb_build_array(
      'Его тело чувствительно только к орудиям, бьющим ИЗ КОСМОСА: снаряды Длани Неотвратимости и баллистика Гиперпейсера. Всё остальное вооружение галактики он не замечает.',
      'Одиночный залп почти бесполезен: он видит снаряд и уходит с траектории — три выстрела из четырёх в пустоту.',
      'Уход с траектории требует внимания. Каждый пришедший снаряд, даже отбитый и даже безвредный, отнимает это внимание на несколько часов. Чем плотнее поток, тем хуже он уворачивается.',
      'Отсюда единственная рабочая связка: дешёвая баллистика Гиперпейсера НЕ РВЁТ его, но глушит; Длань добивает, пока он подавлен. Порознь не работает ни то, ни другое.',
      'Останавливаться нельзя. Несколько часов без попаданий — и всё нанесённое зарастает; в своём логове вдвое быстрее. Кампания, брошенная на середине, не наносит ему вообще никакого ущерба.'),
    'useless', jsonb_build_array(
      'Флот, армия, авиация, минные поля, посты дронов — ноль.',
      'Зенитный огонь его не касается: он не флот, считать в нём нечего.',
      'Ожерелье Немезиды не прикроет от него и не прикроет ЕГО — под чужим Ожерельем он остаётся уязвим.',
      'Взять его измором нельзя: колоний у него нет, отбирать нечего, осаждать нечего.'),
    'note', 'Порядок величин штаб оценивает так: при плотном подавлении речь идёт о трёх-четырёх десятках доведённых залпов Длани. Это работа не одной державы.');
end$$;
grant execute on function public.angel_codex() to authenticated, anon;

-- ── 3. ПАНЕЛЬ ГОВОРИТ ПРАВДУ ИССЛЕДОВАВШЕМУ ─────────────────
-- angel_status чужим отдаёт шум. Теперь «чужой» — это тот, кто НЕ ЗАПЛАТИЛ:
-- исследовавший видит шкалу печатей как есть, и его кампания перестаёт быть
-- стрельбой в темноту.
create or replace function public.angel_status()
returns jsonb language plpgsql security definer set search_path=public as $$
declare a record; me text; mine boolean; seer boolean; f record; frac numeric; sysname text;
begin
  select * into a from public.angel_state order by created_at limit 1;
  if a.faction_id is null then return jsonb_build_object('ok', true, 'exists', false); end if;
  begin me := public._ec_my_fid_opt(); exception when others then me := null; end;
  mine := (me is not null and me = a.faction_id);
  -- ⚠️ Право видеть правду даёт СВОЁ тело или КУПЛЕННОЕ знание, больше ничто.
  seer := mine or (me is not null and public._angel_knows(me));

  select * into f from public.fleets where id = a.fleet_id;
  select coalesce(nullif(name,''), id) into sysname from public.map_systems
   where id = coalesce(f.system_id, f.from_sys, a.home_sys);
  frac := greatest(0, least(1, a.seals / nullif(public._angel_const('seals_max'), 0)));

  return jsonb_build_object(
    'ok', true, 'exists', true, 'fid', a.faction_id, 'mine', mine, 'known', seer,
    'fell', (a.fell_at is not null), 'fell_at', a.fell_at,
    'stance', a.stance, 'system', sysname,
    'moving', (f.status = 'transit'), 'arrive_at', f.arrive_at,
    'seals_word', case when seer then
                    case when a.fell_at is not null then 'пал'
                         when frac > 0.85 then 'целы'
                         when frac > 0.6  then 'тронуты'
                         when frac > 0.35 then 'рвутся'
                         when frac > 0.12 then 'на исходе'
                         else 'последняя' end
                  else public._angel_scream(7) end,
    'seals_frac', case when seer then round(frac, 3) end,
    'salvos_seen', case when seer then a.salvos_seen end,
    'salvos_parried', case when seer then a.salvos_parried end,
    -- совсем точные числа — только своей державе: чужому хватит шкалы
    'seals', case when mine then round(a.seals, 1) end,
    'press', case when mine then round(a.press, 2) end,
    'parry', case when mine then public._angel_parry_p(a.faction_id) end);
end$$;
grant execute on function public.angel_status() to authenticated, anon;

