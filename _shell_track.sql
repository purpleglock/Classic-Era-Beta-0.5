-- ════════════════════════════════════════════════════════════
-- СНАРЯД ПО ФЛОТУ ВЕДЁТ ЦЕЛЬ, А НЕ ТОЧКУ НА КАРТЕ
-- ────────────────────────────────────────────────────────────
-- ПОРЯДОК: после _shell_fleet_hunter.sql / _angel_shells.sql. Отдельный файл:
-- правка не про ангела, а про весь баллистический слой.
--
-- ЧТО БЫЛО НЕ ТАК. `doom_salvos.target_system_id` записывается ОДИН раз, в
-- момент пуска, и больше не меняется. Для залпа по планете это верно — планета
-- никуда не денется. Для залпа по ФЛОТУ — нет: и «Сполох» (Х77), и «Длань» по
-- ковчегу наводятся на тепловую сигнатуру, то есть по правилам летят за целью
-- куда угодно, и резолв так и считает — берёт флот там, где он есть.
--
-- А вот КАРТА об этом не знает: она читает `doom_salvos` напрямую
-- (origin_system_id → target_system_id) и тянет след между двумя точками,
-- интерполируя по launched_at→ready_at. Стоило цели уйти из системы — и след
-- продолжал упираться в пустое место, где её больше нет. Отсюда и «снаряды
-- летят хуй знает куда»: попадали они правильно, а показывали неправду.
-- То же в сводках: «залп по системе X», хотя цель уже в Y.
--
-- ЛЕЧЕНИЕ. Раз в минуту подтягиваем точку прицела к цели:
--   • флот стоит  → целимся в его систему;
--   • флот в пути → целимся туда, КУДА он идёт (dest_sys): снаряд ведёт
--     сигнатуру, и встретятся они там, а не на полдороге;
--   • флота больше нет → точку не трогаем, резолв сам напишет «потерял цель».
-- Время подлёта НЕ пересчитываем: от снаряда, который ведёт сигнатуру, не
-- убегают — это правило слоя, и менять его этой правкой нельзя.
-- ════════════════════════════════════════════════════════════

create or replace function public._shell_track()
returns int language plpgsql security definer set search_path=public as $$
declare n int := 0;
begin
  -- ⚠️ ИМЯ ЦЕЛИ НЕ ТРОГАЕМ. Первая редакция подтягивала и его — и залпы по
  -- ковчегу, подписанные «Престол», разом стали «ОПЛОТ»: наружу уехало
  -- служебное имя флота, которого игрок знать не должен. Ведём ТОЧКУ, подпись
  -- остаётся той, что поставил стреляющий в момент пуска.
  with t as (
    select s.id,
           coalesce(f.system_id, f.dest_sys, f.from_sys) as sys
      from public.doom_salvos s
      join public.fleets f on f.id = s.target_fleet_id
     where s.status = 'in_flight'
       and s.target_fleet_id is not null
  )
  update public.doom_salvos s
     set target_system_id = t.sys
    from t
   where s.id = t.id
     and t.sys is not null
     and s.target_system_id is distinct from t.sys;
  get diagnostics n = row_count;
  return n;
end$$;
revoke all on function public._shell_track() from public;

-- ── КРОН: РАЗ В МИНУТУ ──────────────────────────────────────
-- Дешевле некуда: один UPDATE по горстке строк «в полёте». Ставим отдельным
-- заданием, а не в чей-то тик, — слой общий, и от расписания ангела или
-- Легиона он зависеть не должен.
do $$
begin
  begin perform cron.unschedule('shell-track'); exception when others then null; end;
  begin perform cron.schedule('shell-track', '* * * * *', 'select public._shell_track();');
  exception when others then raise notice 'крон не поставился: %', sqlerrm; end;
end$$;

notify pgrst, 'reload schema';

-- ── ПРОВЕРКА ────────────────────────────────────────────────
-- 1) Пустить «Сполох» по чужому флоту, увести флот в другую систему →
--    след на карте перекладывается за ним в течение минуты.
-- 2) Залп «Длани» по ковчегу, ковчег уходит в прыжок → точка прицела
--    переезжает на систему назначения, сводка называет её же.
-- 3) Флот распущен/уничтожен до подлёта → точка не меняется, резолв пишет
--    «ПОТЕРЯЛ ЦЕЛЬ» и снаряд уходит в пустоту (как и было).

-- ── РАЗОВО: ВЕРНУТЬ ПОДПИСЬ КОВЧЕГУ ─────────────────────────
update public.doom_salvos s
   set target_planet = 'Престол'
  from public.angel_state a
 where s.target_fleet_id = a.fleet_id
   and s.status = 'in_flight'
   and s.target_planet is distinct from 'Престол';

