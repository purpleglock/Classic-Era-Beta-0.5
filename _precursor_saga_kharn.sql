-- ── СРОКИ ──────────────────────────────────────────────────
-- Литоид думает днями, а решает обычаем. Сроки Кхарна нарочно длиннее
-- кайлатских: у камня своё время, и это должно ощущаться неудобством.
insert into public.precursor_saga_wait (world, node, hours) values
  ('kharn', 'w0', 24),    -- пауза литоида после первого разговора
  ('kharn', 'w1', 48),    -- между Счётом и промежутком
  ('kharn', 'w2', 72),    -- сказанное лежит в жиле и остывает
  ('kharn', 'w3', 72),    -- Совет молчит до седмицы
  ('kharn', 'w4', 96)     -- полгода до седмицы смирения
on conflict (world, node) do update set hours = excluded.hours;

-- ── ЦЕНА ИСХОДА ────────────────────────────────────────────
-- ⚠ Долг (§12) не берётся ничем, кроме виры, и вира здесь — их дело, не ваше.
-- Поэтому платит по-настоящему только 'вира': Кхарн открывает устье сам и
-- сам делится (§15, долгая дорога). Всё остальное — либо взято, либо ничто.
--
-- ichor   > 0 — отдано ими самими; < 0 — возвращено вами
-- arrears — насколько гасится недоимка
insert into public.precursor_saga_reward (world, ending, ichor, arrears) values
  ('kharn', 'вира',        40,  120),  -- назвали счёт сами и достояли одиннадцать дней
  ('kharn', 'счёт-назван',  0,   60),  -- произнесено, но числа нет: счёт открыт, не закрыт
  ('kharn', 'устье',       60,    0),  -- короткая дорога: ихор есть, в зачёт не идёт ничего
  ('kharn', 'устье-вира', -60,  140),  -- взятое возвращено в святилище (§15.1)
  ('kharn', 'смирение',     0,    0),  -- не названо ничего: и платить не по чему
  ('kharn', 'подлог',      25,    0),  -- копают охотно и за вашу версию (§11.4)
  ('kharn', 'чужой-счёт',   0,   30)   -- правда сказана мимо державы (крючок `слово`)
on conflict (world, ending) do update
  set ichor = excluded.ichor, arrears = excluded.arrears;
