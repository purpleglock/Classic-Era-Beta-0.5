-- ⚠️ УРОК НА БУДУЩЕЕ: перед revoke надо проверять не только «кто зовёт эту
-- функцию из клиента», но и «нет ли среди вызывающих НЕ-definer функции».
-- Права проверяются по ЭФФЕКТИВНОМУ пользователю в момент вызова, а не по
-- тому, кто функцию написал.
--
-- ЧТО ОТКРЫВАЕМ. Только предикаты чтения, без побочных действий и без тайн:
-- «этот fid — ангел?», «жив ли он», «кто ангел», «константа баланса». Всё это
-- и так публично через angel_status(). Разрушительные двери (вознесение,
-- падение, снятие печатей, вождение ИИ) остаются закрытыми.
