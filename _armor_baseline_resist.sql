-- База стойкости для ШТАТНОЙ брони (+10% ко всем типам урона).
-- Раньше типовые стойкости давал только кастомный сплав (алхимия), а штатная
-- броня имела {kinetic:0,energy:0,missile:0} → окошко «Броня цели» всегда 0%.
-- Теперь штатная броня несёт лёгкую равномерную стойкость, а сплавы её замещают
-- своими (несимметричными) стойкостями ради контр-игры «тип оружия vs броня».
--
-- Плоская броня (summary.armor) как работала, так и работает — это отдельное
-- вычитание урона по корпусу (_war_battle_tactics.sql:644). Здесь только %-стойкости.
--
-- Публикатор уже поправлен (_unit_publish.sql, база 0.1) — новые публикации
-- получат базу автоматически. Этот файл ДОБИВАЕТ уже опубликованные корабли.
-- Безопасность: трогаем ТОЛЬКО те, у кого стойкости нулевые/отсутствуют И нет
-- кастомного сплава — корабли со сплавом (ненулевой resist) не затрагиваются.
-- ════════════════════════════════════════════════════════════

update public.faction_units
   set summary = jsonb_set(
                   coalesce(summary, '{}'::jsonb),
                   '{armor_resist}',
                   jsonb_build_object('kinetic', 0.1, 'energy', 0.1, 'missile', 0.1),
                   true)
 where category = 'ship'
   and nullif(data->>'armorAlloyId', '') is null           -- нет кастомного сплава
   and (
         summary->'armor_resist' is null                    -- поле отсутствует
      or (
           coalesce((summary->'armor_resist'->>'kinetic')::numeric, 0) = 0
       and coalesce((summary->'armor_resist'->>'energy')::numeric, 0) = 0
       and coalesce((summary->'armor_resist'->>'missile')::numeric, 0) = 0
         )                                                  -- либо всё по нулям
       );
