-- ГЛАДИАТОР «КРУПЕЛЛЯРИЙ» — ПЕРЕРАБОТКА В НАСТОЯЩУЮ АРТУ
-- ────────────────────────────────────────────────────────────
-- ЗАЧЕМ. Борт задумывался осадной батареей и носит «Кряж» (осадная
-- платформа: урон ×2, рубеж ×1.25, свёртывание — два хода). Но пушки
-- ему выдали кинетические (idx 4, «Басл»), а вся кинетика на среднем
-- крейсере бьёт на 3 гекса. Получалось: скорость 3, рубеж 3, и модуль,
-- который приколачивает его к месту — «арта», стреляющая в упор и не
-- умеющая отойти. Осада давала 3 → 3.75 гекса, то есть ничего.
--
-- ЧТО МЕНЯЕМ:
--   • оружие: кинетика idx 4 → ВЗРЫВНОЕ idx 5 (ПУ УР-4 «Нови-Сад»),
--     q=2. Рубеж 3 → 30 гексов, с разложенным «Кряжем» — 37.5.
--   • радар 2 → 3: на 30 гексов надо ещё и ВИДЕТЬ цель сквозь завесу.
--   • щит 3 → 2 — плата за рубеж и сенсор; корпус и броня прежние.
--   • модули без изменений: «Кряж» (idx 7) + КАЗ (idx 4).
-- Урон падает с 4594 до ~3108 за залп, но осада удваивает его до ~6216
-- и теперь он доезжает до цели.
--
-- Строка ОБНОВЛЯЕТСЯ на месте (id сохраняется) — живые дуэли и пул
-- драфта на неё ссылаются. Идемпотентно.
-- ════════════════════════════════════════════════════════════

do $$
declare
  v_K    text := 'Конструкционные модули';
  v_data jsonb;
  v_sum  jsonb;
begin
  v_data := jsonb_build_object(
    'class','mediumCruiser','reactor',4,'armor',3,'shield',2,'engine',1,'radar',3,
    'weapons', jsonb_build_array(jsonb_build_object('g','ВЗРЫВНОЕ ВООРУЖЕНИЕ','idx',5,'q',2)),
    'modules', jsonb_build_array(
      jsonb_build_object('g',v_K,'idx',7),     -- осадная платформа «Кряж»
      jsonb_build_object('g',v_K,'idx',4)));   -- КАЗ: пережить ответный залп
  v_sum := public._cn_recompute('ship', v_data);

  update public.faction_units
     set data = v_data, summary = v_sum,
         card_text = 'Латник, который врос в грунт. Пусковые «Нови-Сад» бьют на тридцать гексов, '
                     'а разложенный «Кряж» удваивает урон и отодвигает рубеж ещё на четверть — '
                     'он расстреливает арену с края доски, не сходя с места. Цена честная: '
                     'скорость три, щит тонкий, свёртывание платформы стоит двух ходов. '
                     'Активная защита прикрывает от ракет, пока он перезаряжает свои.'
   where faction_id = 'club' and name = 'Гладиатор «Крупеллярий»';
end $$;

