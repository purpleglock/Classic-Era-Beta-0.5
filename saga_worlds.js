// ════════════════════════════════════════════════════════════
// ДОЗВЁЗДНЫЕ · МИРЫ ХРОНИКИ ИЗ РЕЕСТРА  (этап 12, пункт 1)
//
// Стан (saga_weave.js) умел собрать мир из строки `primitive_civs`, пласты
// (saga_layers.js) умели построить из него главы — но их никто не звал:
// на двери стояли два рукописных мира, а найденные игроком дозвёздные
// оставались списком строк в досье.
//
// Здесь эти три части сведены. На каждый НАЙДЕННЫЙ мир заводится хроника:
//
//     SagaWorlds.bind(civs, fac) → регистрирует по хронике на строку
//
// Ключ хроники — тело, а не рукопись: `civ:<system_id>:<pid>`. Оттого у
// двух игроков, нашедших одну и ту же бухту, хроника одна и та же, а у
// одного игрока в двух системах — две разные.
//
// Мир, которого игрок не находил, не заводится вовсе: дверь показывает то,
// что у державы есть на карте, а не оглавление всего написанного.
//
// ⚠ ГОЛОС (lore/precursor_memory.md §0). Пять правил из saga_layers.js
// действуют и здесь, и к ним шестое, оплаченное забракованным текстом:
// НАДЛОМ НЕ НАЗЫВАЮТ ВСЛУХ. Ни строчки вида «у них травма», «мир не изжил
// беду», «они боятся повторения». Летописец пишет, ЧТО ВИДНО: кто сколько
// взял, кто не пришёл, где стоят и где обходят. Читатель складывает сам —
// или не складывает, и это тоже правда жизни.
// ════════════════════════════════════════════════════════════
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.SagaWorlds = api;
})(typeof window !== 'undefined' ? window : null, function () {
  'use strict';

  const W_ = () => (typeof window !== 'undefined' ? window : {});
  const weave  = () => W_().SagaWeave  || (typeof require === 'function' ? null : null);
  const layers = () => W_().SagaLayers || null;

  // ══════════════════════════════════════════════════════════
  // КОНЦЫ
  //
  // Исход в стане (SagaWeave.FATES) — строка для двери: чем мир стал и как
  // он впадает в стратегию. Сцены у неё там нет, а хроника не может
  // кончаться справкой. Здесь на каждый исход своя последняя сцена.
  //
  // Все они устроены одинаково: посланник приходит в этот мир ЕЩЁ РАЗ,
  // много позже, и смотрит. Ничего не объясняется — называется то, что
  // стоит на месте и чего на месте нет.
  // ══════════════════════════════════════════════════════════
  const КОНЦЫ = {
    'своё_имя': W => [
      `Ваш человек сошёл вниз в последний раз через ${срок(W)}. Его не встречали: `
      + `у ${W.E.узла} стояла очередь, и в очереди стояли не за ним.`,
      `Счёт ведут двое, и второй — молодой, которого при вас не было. Записи `
      + `лежат открыто, и в них есть страница про девять имён. Её не листают `
      + `быстрее прочих.`,
      `Они назвали себя сами, и это имя не то, каким их записали вы. `
      + `Своё имя они выговаривают спокойно, как выговаривают адрес.`,
    ],

    'побратим': W => [
      `Уговор держат ${срок(W)}. Ни разу не переписывали: переписывать значило бы, `
      + `что кто-то из двоих собрался считать заново.`,
      `У ${W.R.старшего} лежит ваш ${W.EP.письмо === true ? 'лист' : 'знак'} — не в `
      + `хранилище, а там, где держат нужное каждый день.`,
      `— С вами мы сговорились. С остальными — торгуем. Это не одно и то же, `
      + `и мы не путаем.`,
    ],

    'долгий_счёт': W => [
      `Виру приняли и приняли не молча: у входа в ${W.E.узел} стоит камень, `
      + `и на нём девять имён, а десятой строкой — сколько за них дали и кто дал.`,
      `Торгуют со всеми. Но всякому, кто приходит впервые, читают эту строку вслух, `
      + `и только потом взвешивают товар.`,
      `${W.R.short[0].toUpperCase() + W.R.short.slice(1)} не мстят. `
      + `${W.R.short[0].toUpperCase() + W.R.short.slice(1)} считают.`,
    ],

    'отпущенные': W => [
      `Голос остался у тех, кто ходил ${W.E.путём} и возвращался ни с чем. `
      + `Теперь ${W.E.путь} их, и возвращаются они полными.`,
      `Товар отпускают любому и по одной цене — своим и чужим, вам и тем, `
      + `кто пришёл после вас.`,
      `Про союз слушают до конца, не перебивая, и отказывают в конце. `
      + `Одинаково всем.`,
    ],

    'ложный_устой': W => [
      `Через ${срок(W)} здесь всё как договорено: сроки, доли, встречи. `
      + `Ваш человек второй раз не нашёл, к чему придраться, и это записал.`,
      `В записи, которую вам показывают, страница про девять имён есть. `
      + `Она написана одной рукой и одними чернилами — вся, от первой строки `
      + `до последней, включая ту, что старше остальных на поколение.`,
      `Их корабли ходят дальше, чем должны на этом веку. Куда — в записи нет.`,
    ],

    'возвратный_ход': W => [
      `Здесь пусто, и пусто не от беды: ${W.R.short} ушли сами и ушли вверх.`,
      `На соседнем теле, за две системы отсюда, пропали трое. Через ${срок(W)} `
      + `там пропало сорок. Считают их не там, где они жили, а там, куда их свезли.`,
      `Они делают ровно то, что было сделано с ними, и делают точнее: `
      + `у них есть, с чего списывать.`,
    ],

    'немой_век': W => [
      `Ничего не случилось. ${срок(W)[0].toUpperCase() + срок(W).slice(1)} ничего `
      + `не случалось, и это единственное, что можно записать.`,
      `Счёт ведут, но коротко. ${W.EP.письмо === true
        ? 'Записи стали втрое тоньше прежних.' : 'Вслух говорят втрое меньше прежнего.'}`,
      `Ваш пост внизу свернули за ненадобностью. Смотреть там не на что — `
      + `пока не на что.`,
    ],

    'смута': W => [
      `Власть у ${W.E.узла} менялась ${W.EP.порох ? 'четыре раза' : 'семь раз'}, `
      + `и последние двое уже не помнят, с чего начали.`,
      `Счёт не ведёт никто: всякий, кто садился считать, оказывался виноват `
      + `в том, что насчитал.`,
      `Наружу лезут малыми ватагами. Не за землёй — за тем, что можно унести `
      + `и продать до вечера.`,
    ],

    'осыпь': W => [
      `Ни пожара, ни следа драки. Ушли по одному, в разные стороны, `
      + `и по дороге разошлись окончательно.`,
      `${W.EP.письмо === true ? 'Записи остались лежать там, где их вели.'
        : 'Спросить не у кого: тех, кто держал счёт в голове, больше нет.'}`,
      `Ихор остался внизу. Достать его теперь не у кого спросить и некому отдать.`,
    ],

    'выскобленные': W => [
      `Выработка стоит до сих пор. Она пережила тех, ради кого её ставили.`,
      `${W.R.short[0].toUpperCase() + W.R.short.slice(1)} остались, но их мало `
      + `и они не считают: считать нечего.`,
      `На картах соседей эта система помечена вашим знаком. Помечена не вами.`,
    ],

    'спящая_вещь': W => [
      `Вы ушли, и внизу это заметили не сразу, а заметив — вписали одной строкой `
      + `и вернулись к своему.`,
      `Мир идёт как шёл: ${W.E.узел}, ${W.E.путь}, ${W.E.беда} раз в поколение.`,
      `Он достанется следующему. Следующим можете быть не вы.`,
    ],
  };

  // Срок называют ИХ мерой времени, а не годами: год — наша единица, внизу
  // о ней не знают. Форма готовая (R.двое), потому что «два вспышки» —
  // это машина, а не летописец.
  const срок = W => W.R.двое || 'две смены луны';

  // Последняя строка хроники — про вашего человека, и только про него.
  // Здесь же игрок узнаёт, что отчёты, по которым он решал, сходились не со
  // всем. Сказано это ровно один раз и без объяснений: объяснять нечего,
  // счёт уже закрыт.
  function человек(W) {
    const e = (W.живое && W.живое().посланник) || null;
    if (!e || !e.имя) return '';
    // Ни падежей на имени, ни глаголов в прошедшем: имя приходит из списка
    // расы или из совета, и ни рода его, ни склонения мы не знаем. «Журнал
    // Валга-дипломат сверили» — это машина. Оттого имя стоит только в
    // именительном, а сказуемое либо в настоящем, либо безличное.
    if (e.сломан) {
      return `${e.имя} наверх не вернётся. Последний челнок ушёл пустым.`;
    }
    if (e.прикипел) {
      return `${e.имя} просит оставить себя при этом мире. В прошении трижды `
        + `стоит «мы» — и это «мы» не про вас.`;
    }
    if (e.лжёт) {
      return `Журнал с подписью «${e.имя}» сверили с записью летописца. `
        + `Сходятся не везде, и все расхождения в одну сторону — в главах, `
        + `после которых решали вы.`;
    }
    return `${e.имя} сдаёт журнал и просит другой мир.`;
  }

  // ══════════════════════════════════════════════════════════
  // СБОРКА ОДНОГО МИРА
  // ══════════════════════════════════════════════════════════
  function make(civ, fac) {
    const WV = weave(), LY = layers();
    if (!WV || !LY) return null;

    const W = WV.world(civ, fac);
    W.живое = () => {
      const PS = W_().PrecursorSaga;
      return (PS && PS.ST && PS.ST[W.id]) || {};
    };
    const built = LY.build(W);

    // Концы: узел на исход. `end` — id исхода, его же сервер кладёт в след,
    // по нему же считается цена (precursor_saga_reward).
    const ENDINGS = {};
    WV.FATES.forEach(f => {
      const txt = (КОНЦЫ[f.id] || КОНЦЫ['спящая_вещь'])(W).concat([() => человек(W)]);
      built.NODES['end_' + f.id] = { ep: W.EP.ep, who: 'obs', end: f.id, t: txt };
      ENDINGS[f.id] = [f.имя, f.txt];
    });
    // Пласты уводят на 'end_спящая' — у пластов своё имя для того же конца.
    built.NODES['end_спящая'] = built.NODES['end_спящая_вещь'];

    W.NODES   = built.NODES;
    W.ENDINGS = ENDINGS;
    W.first   = built.first;
    // Развязка: движок, дойдя до узла с resolve, зовёт это и получает, куда идти.
    W.resolve = flags => 'end_' + WV.fate(LY.resolve(flags, W)).id;
    // Дверь: своей карточки у найденного мира нет, идём на сетку «раса × эпоха».
    W.art = null;
    return W;
  }

  // ══════════════════════════════════════════════════════════
  // ПРИВЯЗКА К РЕЕСТРУ
  //
  // civs — то, что вернул precursor_get: строки primitive_civs, видимые
  // державе. fac — кто смотрит: раса и доктрина ВАШЕЙ державы (их отдаёт
  // precursor_saga_get). Мёртвые и вышедшие к звёздам хроники не заводят:
  // у первых некому говорить, вторые уже не дозвёздные.
  // ══════════════════════════════════════════════════════════
  function bind(civs, fac) {
    const PS = W_().PrecursorSaga;
    if (!PS || !weave() || !layers()) return 0;
    let n = 0;
    (civs || []).forEach(civ => {
      if (!civ || !civ.system_id) return;
      if (civ.status === 'dead' || civ.status === 'spacefaring') return;
      const id = weave().key(civ);
      if (PS.WORLDS[id]) return;          // уже заведён — след в нём уже лежит
      const W = make(civ, fac);
      if (W) { PS.register(id, W); n++; }
    });
    return n;
  }

  return { bind, make, КОНЦЫ };
});
