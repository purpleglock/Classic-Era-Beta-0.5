-- ════════════════════════════════════════════════════════════
-- «ЛОРЕЛЕЯ» → РЕМОНТНЫЙ ТЕНДЕР
-- ────────────────────────────────────────────────────────────
-- Общедоступный фрахтовщик (176 построенных бортов) не делал НИЧЕГО:
-- dmg 0, огневых групп нет, cargo 90 никуда не подключён. Даём нано-рой:
-- лечит союзников, сам не бьёт вовсе.
--
-- ⚠ ЛЕГАСИ-ТТХ ПРИВЕДЕНЫ К ОБЩЕЙ ШКАЛЕ (броня 4200 → 0, щит 5000 → 200,
-- скорость 40 → 14, hp 500 → 1575 = обычный корвет).
-- Почему броня ОБЯЗАНА быть нулём: в battle_fire
--     hull := greatest(total_dmg * 0.10, hull_leak - armor)
-- любая броня больше входящего урона прижимает урон к полу в 10%.
-- У ВСЕХ современных кораблей armor = 0 (_cn_recompute сворачивает броню
-- в hp), и «Лорелея» была единственной, кто этот пол эксплуатировал:
-- рой мелких кораблей не мог её убить в принципе (18-24 атаки «Эквитом»
-- против 6 по обычному корвету), зато крупный калибр сносил за 2.
-- Промежуточные значения не спасают: даже с бронёй 800 выходило 41 атака.
-- Живучесть теперь только от скорости — как и задумано для тендера.
--
-- ⚠ ПОЧЕМУ ХИРУРГИЧЕСКИ, А НЕ ЧЕРЕЗ _cn_recompute:
-- дизайн легаси и на нынешнем каталоге НЕ ПЕРЕСЧИТЫВАЕТСЯ — падает с
-- 'bad reactor' (data.reactor=3, а у корвета сейчас 3 реактора: 0..2),
-- плюс hangars/type в каталоге кораблей больше не существуют
-- (defs.ship: hasHangars=false, hasType=false). Любой пересчёт либо
-- упадёт, либо снесёт легаси-броню/щит/скорость и обнулит 176 бортов.
-- Поэтому правим ТОЧЕЧНО: weapons в data + пара полей summary.
--
-- ⚠ ПОЧЕМУ У ТУРЕЛИ СИНТЕТИЧЕСКИЙ fid, А НЕ null:
-- _cn_wpn_obj пускает игрока к турели, если она его, ЛИБО faction_id is null.
-- Публичная турель с carriers={corvette} позволила бы ЛЮБОМУ повесить
-- нано-ремонт на свой корвет — а глобальное правило «нано только на средний
-- крейсер» (_tg_carriers) должно устоять. Ковать такое игрок и не может:
-- klass 'light' (единственный с корветом в classCarriers) техники nano не
-- имеет вовсе. Синтетический fid закрывает доступ, а _bt_stats прав доступа
-- не проверяет — «Лорелея» свою ремонтную группу в бою получает.
-- ════════════════════════════════════════════════════════════
do $$
declare
  -- owner_id у faction_turrets NOT NULL; fid синтетический — доступа игрокам нет
  v_staff   uuid := 'aae388fd-c3ed-4592-bad0-7a61e32e9b00';
  v_kitfid  text := 'pancolonial';
  v_cfg     jsonb := '{"klass":"medium","tech":"nano","caliber":110,"barrels":1,"barrelLen":50,"size":0.8,"layout":"row"}'::jsonb;
  v_kit     uuid;
  v_unit    uuid;
  v_stats   jsonb;
begin
  select id into v_unit from public.faction_units
   where faction_id is null and name = 'Пан-колониальный фрахтовщик «Лорелея»';
  if v_unit is null then raise exception '«Лорелея» не найдена — нечего дорабатывать'; end if;

  delete from public.faction_turrets where faction_id = v_kitfid and name = 'Ремкомплект «Лорелея-Т»';

  v_stats := public._tg_stats(v_cfg);
  insert into public.faction_turrets (owner_id, faction_id, name, cfg, stats, carriers)
  values (v_staff, v_kitfid, 'Ремкомплект «Лорелея-Т»',
          public._tg_norm(v_cfg), v_stats,
          -- carriers прописаны вручную: это штучный тендерный набор под корвет,
          -- глобальное правило _tg_carriers (nano → mediumCruiser) не трогаем.
          array['corvette']::text[])
  returning id into v_kit;

  update public.faction_units
     set data = jsonb_set(data, '{weapons}',
                  jsonb_build_array(jsonb_build_object('turretId', v_kit::text, 'q', 1))),
         -- ТТХ на общую шкалу + цена с 565 до корветной планки (между
         -- «Велитом» 13 885 и «Эквитом» 20 282). 176 уже построенных бортов
         -- остаются у владельцев по старой цене — дорожают только НОВЫЕ.
         summary = summary || jsonb_build_object(
                      'hp',     1575,   -- как у штатного корвета с ККБ-54
                      'armor',  0,      -- см. шапку: ненулевая броня = пол в 10%
                      'shield', 200,    -- потолок щита для класса «корвет»
                      'speed',  14,     -- быстрее всех (max 10), но не вчетверо
                      'cost',   16000),
         card_text = 'НАЗВАНИЕ: ПАН-КОЛОНИАЛЬНЫЙ ТЕНДЕР «ЛОРЕЛЕЯ»' || chr(10) ||
           'Класс: Корвет (ремонтный тендер)' || chr(10) ||
           '------------------------------------------' || chr(10) ||
           'КОРПУС: 1 575 HP · ЩИТЫ: 200 · БРОНЯ: нет' || chr(10) ||
           'СКОРОСТЬ: 14 — быстрее любого корабля флота' || chr(10) ||
           '------------------------------------------' || chr(10) ||
           'РЕМОНТНЫЙ РОЙ «Лорелея-Т»: +' ||
             coalesce(v_stats->>'heal','0') || ' корпуса союзнику, до ' ||
             coalesce(v_stats->>'dalnost','0') || ' гекс.' || chr(10) ||
           'Оружия нет и не будет: тендер не стреляет вовсе.' || chr(10) ||
           'Себя починить не может — только ДРУГОЙ корабль.' || chr(10) ||
           '------------------------------------------' || chr(10) ||
           'Живучести нет: обычный корвет, который убивают с одного' || chr(10) ||
           'залпа. Всё, что у него есть, — скорость: подъехать к' || chr(10) ||
           'подбитому, поставить на ноги и убраться из-под удара.' || chr(10) ||
           'В бою светится как выстреливший — латая, выдаёт себя.',
         updated_at = now()
   where id = v_unit;

  raise notice 'Лорелея → тендер: turret=%, heal=%, дальность=%',
    v_kit, v_stats->>'heal', v_stats->>'dalnost';
end $$;
