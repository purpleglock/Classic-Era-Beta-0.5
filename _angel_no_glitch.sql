-- «ПРЕСТОЛ» — ПОМЕХИ СНЯТЫ СО ВСЕЙ ЛЕНТЫ
-- ────────────────────────────────────────────────────────────
-- ПОРЯДОК: после _angel_lines_hook.sql. Надмножество `_angel_glitch`,
-- `_angel_scream`, `_angel_cause`. Идемпотентно.
--
-- ЗАЧЕМ ТАК, А НЕ ПО ФАЙЛАМ. Глитченых заголовков в цепочке 45 штук в 11
-- файлах. Переписывать каждый вызов — это одиннадцать надмножеств, и любое
-- из них рискует откатить чужую правку, накатанную позже. Дешевле и честнее
-- снять помехи в ОДНОЙ точке: у самих генераторов.
--
-- ПОЧЕМУ ВООБЩЕ СНИМАЕМ.
--   1) Атмосфера. Побитый случайными символами канцелярит читается как
--      машинный мусор, а не как жуть. Голос кризиса теперь есть отдельно
--      (_angel_lines.sql) — короткие написанные реплики на «ты». Помехи ему
--      только мешают: рядом с настоящей репликой шум выглядит подделкой.
--   2) Это был ещё и БАГ. Часовая сводка в беседу группирует новости ПО
--      ЗАГОЛОВКУ. `_angel_glitch` мангляет заголовок СЛУЧАЙНО при каждом
--      вызове, поэтому семь одинаковых событий давали семь разных заголовков,
--      группировка разваливалась и в беседу уезжала стена нечитаемого текста.
--      ⚠️ ОБЩЕЕ ПРАВИЛО: любой повторяемый текст, прогнанный через рандом,
--      ломает всякую дедупликацию ниже по течению. Не рандомизировать то,
--      по чему потом группируют.
--
-- ЧТО ВМЕСТО.
--   • `_angel_glitch` возвращает текст КАК ЕСТЬ. Все 45 мест разом становятся
--     читаемой прозой со стабильными заголовками.
--   • `_angel_scream` возвращает многоточие вместо шума. Он стоял там, где
--     фраза обрывается на месте ответа («Оценка ущерба » + шум) — с пустой
--     строкой такие места читались бы как обрезанные, а с многоточием
--     работают ровно как задумано: прибор не ответил. И оно стабильно.
--
-- ⚠️ ПОВОД ВОЙНЫ — ИСКЛЮЧЕНИЕ. Там шум нужен по смыслу: в графе «причина»
-- стоит не язык (см. _angel_cause.sql). У него теперь свой генератор, не
-- зависящий от `_angel_scream`, иначе повод превратился бы в «◈ Причина: …».
-- ════════════════════════════════════════════════════════════

-- ── 1. ПОМЕХ НЕТ ────────────────────────────────────────────
create or replace function public._angel_glitch(p_text text, p_rate numeric default 0.30)
returns text language sql immutable as $$
  select p_text
$$;

create or replace function public._angel_scream(p_len int default 12)
returns text language sql immutable as $$
  select '…'
$$;

-- ── 2. ШУМ ТАМ, ГДЕ ОН ПО СМЫСЛУ ────────────────────────────
-- Свой генератор для повода войны. Раньше звал `_angel_scream`, а тот теперь
-- многоточие — повод стал бы пустым.
create or replace function public._angel_noise(p_len int default 14)
returns text language plpgsql volatile as $$
declare gl text[] := array['▓','░','▒','█','╳','╬','┼','⌁','⟊','⟟','⍜','⏢','⨯','⩫','▚','▞','▟'];
        out text := ''; i int;
begin
  for i in 1 .. greatest(1, p_len) loop
    out := out || gl[1 + floor(random() * array_length(gl,1))::int];
  end loop;
  return out;
end$$;
revoke all on function public._angel_noise(int) from public;

create or replace function public._angel_cause()
returns text language sql volatile as $$
  select '◈ Причина: ' || public._angel_noise(14)
$$;
revoke all on function public._angel_cause() from public;

notify pgrst, 'reload schema';

-- ── 3. ПРОВЕРКА ─────────────────────────────────────────────
do $$
begin
  raise notice 'заголовок был бы: «%»',
    public._angel_glitch('◈ Над системой', 0.20);
  raise notice 'обрыв фразы: «Оценка ущерба %»', public._angel_scream(13);
  raise notice 'повод войны: «%»', public._angel_cause();
  raise notice 'повод войны: «%»  (шум у каждой войны свой)', public._angel_cause();
end$$;
