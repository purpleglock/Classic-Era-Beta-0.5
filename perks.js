function perkClassOk(p, cls) {
  if (!p || !p.cls) return true;
  return (Array.isArray(p.cls) ? p.cls : [p.cls]).includes(cls);
}
// app — строка faction_applications (gov / ideology).
function perkGateOk(p, app) {
  if (!p || !p.gate) return true;
  if (!app) return false;
  if (p.gate === 'faith') return app.ideology === 'Спиритуализм' || app.gov === 'Теократия';
  if (p.gate === 'ai')    return app.gov === 'Машинный разум (ИИ)';
  if (p.gate === 'hive')  return app.gov === 'Коллективный разум';
  return true;
}
function perkLine(p) { return p.eff; }
// Числа, проценты и секунды — акцентом: строку эффекта читают глазами, не текстом.
function perkNums(s) {
  return String(s).replace(/([+−-]?\d+(?:\.\d+)?\s*(?:%|c\b|ход[а-я]*|гекс[а-я]*)?)/g,
    m => `<b>${m}</b>`);
}
