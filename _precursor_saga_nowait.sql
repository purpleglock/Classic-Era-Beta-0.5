-- ХРОНИКА · СРОКИ СНЯТЫ С ЧТЕНИЯ  (этап 12, пункт 9)
--
-- Было: 6 ч на прологе (p2), 12 ч на d0/r0, 24 ч на f0. Игрок упирался в
-- таймер на третьем экране, ещё ничего не решив, и закрывал вкладку. Срок
-- стоял на узлах ПОВЕСТВОВАНИЯ — то есть ждать надо было, чтобы прочитать
-- следующий абзац. Это не «держава не отвечает раньше своего дня», это
-- заперть за чтение.
--
-- Стало: ждать можно только там, где игрок ЧТО-ТО ОТПРАВИЛ и ждёт ответа
-- с той стороны. Таких мест два, и оба по часу:
--   w_2 — посланник ушёл, слово расходится;
--   w_3 — виру собирают.
-- Всё остальное читается подряд.
--
-- Накат идемпотентный. Отменяет и заменяет _precursor_saga_waits.sql.
-- ════════════════════════════════════════════════════════════

-- 1. Снять срок со всех повествовательных узлов — всех разом, а не списком:
--    список уже дважды отставал от того, что написано в мирах.
--
--    ⚠ И СНЯТЬ ПЕРЕОПРЕДЕЛЕНИЯ ПО МИРУ. `_pc_saga_wait` ищет сначала строку
--    своего мира и только потом общую '*'. У Кайлата на w_2/w_3 лежало по
--    68 часов — почти трое суток, — и общий срок их не перебивал: правку
--    общей строки просто не читали. Оттого первая попытка «снять сроки»
--    ничего не изменила. Мир своих сроков не держит: одна общая полка.
delete from public.precursor_saga_wait
 where world <> '*' or node not in ('w_2', 'w_3');

-- 2. Оставшимся двум — по часу.
insert into public.precursor_saga_wait (world, node, hours, note) values
  ('*', 'w_2', 1, 'Посланник ушёл: слово расходится не мгновенно'),
  ('*', 'w_3', 1, 'Виру собирают')
on conflict (world, node) do update
  set hours = excluded.hours, note = excluded.note;

-- 3. Развязать тех, кто уже стоит под старым сроком: сдвинуть отметку в
--    прошлое, иначе накат снимет правило, а зависшие записи досидят свои
--    сутки по старому updated_at.
update public.precursor_saga
   set updated_at = now() - interval '48 hours'
 where updated_at > now() - interval '48 hours';
