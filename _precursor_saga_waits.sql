-- Было: срок стоял на узлах глав (p2, d0, r0, f0) — то есть игрок упирался
-- в «вернитесь через сутки» посреди разговора, на полуслове.
-- Стало: срок стоит на ВЫДЕРЖКАХ (w_1, w_2, w_3) — отдельных сценах между
-- главами, которые для того и написаны: там ничего не решается, там просто
-- проходит время. Глава кончается, выдержка показывает, что за это время
-- стало, и дальше хроника ждёт.
--
-- Накат идемпотентный, порядок — после _precursor_saga_civs.sql.
-- ════════════════════════════════════════════════════════════

delete from public.precursor_saga_wait
 where world = '*' and node in ('p2', 'd0', 'r0', 'f0', 'f_сами');

insert into public.precursor_saga_wait (world, node, hours, note) values
  ('*', 'w_1',  6, 'Между тем, что увидели, и тем, что сделали'),
  ('*', 'w_2', 12, 'Сказанное расходится не сразу'),
  ('*', 'w_3', 24, 'Виру собирают долго и собирают не всю')
on conflict (world, node) do update
  set hours = excluded.hours, note = excluded.note;
