-- ============================================================
-- БОЛЬШАЯ АРЕНА: 60×80 → 60×60
-- ============================================================
-- Зачем: доска ИИ-боёв 60×80 — это ~3000×4700 мировых единиц. Камера
-- физически не показывает её целиком, игрок смотрит в окно размером с
-- десятую часть поля и видит пустоту вместо флота. По высоте поле резалось
-- вслепую: 80 рядов ни один бой не использовал (максимум занятого ряда в
-- живых боях — 41).
--
-- Что меняется:
--   • _bt_hbig() 80 → 60. Новые крупные бои (ИИ, встречные) = 60×60.
--   • Уже созданным боям с bh=80 высота ужимается до 60 — но ТОЛЬКО тем, где
--     ни один борт не стоит ниже 60-го ряда (иначе корабль оказался бы за
--     краем доски). Ландшафт таких боёв обрезается по новой высоте: он лежит
--     снимком в battles.terrain, и камни ниже края висели бы в пустоте.
-- Дуэли клуба (48×28) не трогаются: у них своя, маленькая арена.
-- ============================================================

create or replace function public._bt_hbig() returns int
language sql immutable as $$ select 60 $$;

-- Ужать уже созданные большие бои, где это безопасно
update public.battles b
   set bh = 60,
       terrain = (
         select coalesce(jsonb_agg(t), '[]'::jsonb)
           from jsonb_array_elements(coalesce(b.terrain, '[]'::jsonb)) t
          where (t->>'y')::int < 60)
 where b.bh = 80
   and coalesce((select max(u.y) from public.battle_units u where u.battle_id = b.id), 0) < 60;

