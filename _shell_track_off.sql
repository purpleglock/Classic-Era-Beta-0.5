-- ПОРЯДОК: после _shell_track.sql. Отменяет его целиком.
--
-- ЧТО БЫЛО СДЕЛАНО И ПОЧЕМУ ЭТО НЕВЕРНО. Чтобы след залпа не упирался в
-- систему, которую цель уже покинула, крон раз в минуту переписывал
-- `doom_salvos.target_system_id` на текущее место флота-цели. Механику это не
-- трогало (резолв и так берёт флот там, где он есть), но картинку сделало
-- хуже, а не лучше:
--   • карта строит ДУГУ между двумя звёздами (origin → target) и гонит по ней
--     искру по доле прошедшего времени. Сдвиг конца дуги = мгновенный прыжок
--     всей траектории и самой искры вбок. Раз в минуту, у каждого залпа;
--   • красное кольцо цели переезжало на звезду, по которой игрок не стрелял, —
--     «удар идёт по системе, в которую я не стрелял»;
--   • сводка о пуске называла одну систему, карта показывала другую.
--
-- ПРАВИЛЬНОЕ МЕСТО ПРАВКИ — КЛИЕНТ, А НЕ БАЗА. Запись о залпе должна хранить
-- то, что было в момент пуска (это факт, и по нему написана сводка), а
-- «снаряд ведёт сигнатуру» — это про ОТРИСОВКУ: если у залпа есть
-- `target_fleet_id`, карта сама тянет конец дуги к текущему месту этого флота
-- (см. gmmBuildSalvos в galaxy_map.js). Тогда и кольцо стоит на цели, по
-- которой стреляли, и никакой записи в базу каждую минуту.
-- ════════════════════════════════════════════════════════════

do $$
begin
  begin perform cron.unschedule('shell-track'); exception when others then null; end;
end$$;

drop function if exists public._shell_track();

notify pgrst, 'reload schema';

