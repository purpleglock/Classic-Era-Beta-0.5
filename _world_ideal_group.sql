-- ПОРЯДОК: после _world_classes.sql. Идемпотентно.
--
-- ЧТО НАШЛОСЬ НА ПРОВЕРКЕ. `_world_kind` берёт класс по флагу `ideal` и всё
-- считает верно, но ВЕСЬ ОСТАЛЬНОЙ мир игры (колонизация, терраформ, станции)
-- ходит через `_ec_group_of`, а тот про новый тип не знал: `_ec_planet_group`
-- возвращал 'unknown', и группа доставалась ИМЕНЕМ планеты. «Мегаастероид»
-- превращался в micro, «Главный пояс астероидов» — в 'unknown' с тиром
-- терраформа 3, то есть рай на месте переплавленного мира заселялся как
-- экстремальный мир за 4 800 ГС.
--
-- ⚠️ `_ec_planet_group` живёт в экономических файлах и переписывается там
-- целиком (см. defense-const-clobber): при следующем накате экономики эту
-- строку надо ВЕРНУТЬ. Ветка одна и добавлена в конец списка.
-- ════════════════════════════════════════════════════════════
create or replace function public._ec_planet_group(p_type text)
returns text language sql immutable as $$
  select case btrim(coalesce(p_type,''))
    when 'Лавовые миры'    then 'lava'      when 'Вулканические' then 'volcanic'
    when 'Землеподобные'   then 'terrestrial' when 'Океанические' then 'oceanic'
    when 'Пустынные'       then 'desert'    when 'Криомиры'      then 'cryo'
    when 'Газовые гиганты' then 'gasgiant'  when 'Ледяные гиганты' then 'icegiant'
    when 'Горячие гиганты' then 'hotgiant'  when 'Экзотические'  then 'exotic'
    when 'Малые тела'      then 'micro'     when 'Аномалии'      then 'anomaly'
    -- ⟨ПРИРОДА МИРА⟩ идеальный мир заселяется как самый дружелюбный обычный:
    -- свои множители он получает отдельно, по флагу `ideal` (_world_kind).
    when 'Идеальный мир'   then 'terrestrial'
    else 'unknown' end
$$;

