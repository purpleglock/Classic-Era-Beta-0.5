// Замер партии: доигрываем до конца разными руками и смотрим, что
// выходит. Кнопок не проверяем — проверяем, что игра вообще РЕШАЕМАЯ и что
// у неё есть больше одного конца.
const R = require('../precursor_run.js');

const мир = { anchor: { wounds: [{ state: 'вскрытый' }, { state: 'вскрытый' }] } };
const событие = { имя: 'событие', цена: 0, русло: 4, надлом: 0 };

function партия(имя, ход) {
  let r = R.завести(мир);
  // Казна и досье Фонда приходят из precursor_get; в замере ставим их руками,
  // иначе действия с ценой отобьются «казна не тянет» и мерка соврёт.
  r.казна = 20000000; r.фонд = 0;
  const старт = { русло: r.русло, надлом: r.надлом };
  let век = 0;
  while (!r.конец && век < 40) {
    век++;
    ход(r).forEach(id => { const x = R.ступень(r, id); if (x.ok) r = x.run; });
    const d = R.решить(r, событие); if (d.ok) r = d.run;
    const v = R.век(r); if (v.ok) r = v.run; else break;
  }
  console.log(`${имя.padEnd(24)} → ${String(r.конец).padEnd(8)} `
    + `развитие ${String(r.русло).padStart(3)} ущерб ${String(r.надлом).padStart(3)}`
    + ` · Фонд ${String(r.фонд).padStart(4)} · потрачено ${
      (r.потрачено / 1e6).toFixed(1)}М ГС · веков ${r.ход}`);
  return r;
}

// Обряд стратегией быть не может: он не ступень, а выход из партии в один
// клик (см. `обряд: true` в РУКЕ). Здесь проверяем ровно это — что он НЕ
// проходит `ступень()`, иначе мир снова можно будет вычистить кнопкой хода.
const обр = R.РУКА.find(x => x.обряд);
const отказ = R.ступень(Object.assign(R.завести(мир), { казна: 20000000 }), обр.id);
if (отказ.ok) { console.error('ПРОВАЛ: обряд прошёл обычной ступенью'); process.exit(1); }
console.log(`обряд ступенью не проходит → «${отказ.why}»
`);

const a = партия('Слово, потом Покой', r => r.внимание >= 2 && r.ход < 6 ? ['слово'] : ['покой']);
const b = партия('Ритм и Покой', r => r.внимание >= 2 ? ['ритм'] : ['покой']);
const c = партия('Слово каждый век', r => r.внимание >= 2 ? ['слово'] : ['покой']);
const d = партия('ничего не делать', () => []);

const концы = new Set([a.конец, b.конец, c.конец, d.конец]);
console.log('\nразных концов:', concов_(концы), [...концы].join(', '));
function concов_(s) { return s.size; }
if (concов_(концы) < 2) { console.error('ПРОВАЛ: у партии один конец на все руки'); process.exit(1); }
const свежая = R.завести(мир); свежая.казна = 20000000;
if (!R.можно(свежая, 'ритм').ok) { console.error('ПРОВАЛ: первый ход нечем ходить'); process.exit(1); }
// И обратное: без денег дорогое действие обязано отбиваться причиной, а не молча.
const нищая = R.завести(мир); нищая.казна = 0;
if (R.можно(нищая, 'ритм').ok) { console.error('ПРОВАЛ: платное действие прошло с пустой казной'); process.exit(1); }
