// ── ВЫНОС ТЕКСТА ПОЛОК В ДАННЫЕ ──────────────────────────────────────────────
// Реплики полок написаны функциями: `W => 'Со стороны ' + W.E.узла + ' вышел
// один'`. Пока текст — код, его нельзя ни отредактировать в верстаке, ни
// выгрузить файлом: правка требует программиста на каждую запятую.
//
// Скрипт зовёт каждую такую функцию с ПОДСТАВНЫМ миром — прокси, который на
// всякое обращение возвращает не значение, а метку своего пути. Склейка строк
// делает остальное сама: на выходе та же фраза, но с дырами вместо значений —
// 'Со стороны {W.E.узла} вышел один'. Разбирать исходник не нужно.
//
//   node tools/saga_text_extract.js          — показать, что получится
//   node tools/saga_text_extract.js --write  — записать saga_text.js
//
// ⚠ Метка нарочно начинается с латинской «q»: `Б()` поднимает первую букву
// фразы, и по «Q» видно, что дыру подставляли с большой буквы. Без этого
// заглавные молча терялись бы по всему тексту.
'use strict';
const fs = require('fs'), path = require('path');
const KIT = require('../saga_kit.js');

const МЕТКА = (p) => 'q\u0001' + p + '\u0001p';
const РАЗБОР = /([qQ])\u0001([^\u0001]+)\u0001p/g;

// Прокси-мир: любое обращение вглубь копит путь, а превращение в строку
// отдаёт метку. Числа и сравнения сюда не заходят — полки ветвлений не имеют
// (проверено: 107 функций, 0 с `?` и `if`).
function подстава(путь) {
  const f = function () {};
  f.__путь = путь;
  return new Proxy(f, {
    get(t, k) {
      if (k === Symbol.toPrimitive) return () => МЕТКА(путь);
      if (k === 'toString' || k === 'valueOf') return () => МЕТКА(путь);
      if (k === '__путь') return путь;
      if (typeof k === 'symbol') return undefined;
      return подстава(путь + '.' + String(k));
    },
    apply() { return подстава(путь + '()'); },
  });
}

function шаблон(x, корни) {
  const s = typeof x === 'function' ? x.apply(null, корни.map(подстава)) : x;
  if (Array.isArray(s)) return s.map(v => шаблон(v, корни));
  return String(s).replace(РАЗБОР, (m, ч, п) => '{' + (ч === 'Q' ? 'Б:' : '') + п + '}');
}

// ── что выносим ──────────────────────────────────────────────────────────────
const ТЕМЫ = KIT.ТЕМЫ.map(t => ({
  id: t.id, имя: t.имя, сост: t.сост, ступень: t.ступень, линия: t.линия, хорошо: t.хорошо,
}));

const НУЖДЫ = {};
Object.keys(KIT.НУЖДЫ).forEach(роль => {
  НУЖДЫ[роль] = KIT.НУЖДЫ[роль].map(н => ({
    нужда:    шаблон(н.нужда, ['W']),
    помеха:   шаблон(н.помеха, ['W']),
    скрывает: шаблон(н.скрывает, ['W']),
  }));
});

// Гейт остаётся кодом и в файл не идёт: это не текст, а условие («у них есть
// руки», «эта среда — не вода»). Полки сводятся с гейтами по `id`.
const РУЖЬЯ = KIT.РУЖЬЯ.map(р => ({
  id: р.id, среда: р.среда,
  сад:  шаблон(р.сад, ['W']),
  ход:  шаблон(р.ход, ['W']),
  бой:  шаблон(р.бой, ['W']),
  замок: шаблон(р.замок, ['W']),
}));

const ГРУЗЫ = KIT.ГРУЗЫ.map(г => ({ id: г.id, n: г.n }));

const СОБЫТИЯ = {};
Object.keys(KIT.СОБЫТИЯ).forEach(крючок => {
  СОБЫТИЯ[крючок] = KIT.СОБЫТИЯ[крючок].map(с => ({
    id: с.id, имя: с.имя,
    факты: шаблон(с.факты, ['W', 'Л']),
    решение: шаблон(с.решение, ['W', 'Л']),
  }));
});

// ── запись ───────────────────────────────────────────────────────────────────
const j = o => JSON.stringify(o, null, 2)
  .replace(/\n/g, '\n  ')                       // отступ под тело модуля
  .replace(/"([^"\\]*)"/g, (m, s) => "'" + s.replace(/'/g, "\\'") + "'");

const ШАПКА = `// ════════════════════════════════════════════════════════════
// ХРОНИКИ · ТЕКСТ ПОЛОК
//
// Тут лежат ФРАЗЫ, и больше ничего. Ни условий, ни склейки, ни расчётов —
// всё это осталось в saga_kit.js. Сделано затем, чтобы текст правился без
// программиста: в консоли (вкладка «📜 Хроника») и выгружался обратно этим
// же файлом.
//
// ДЫРА в фразе — {W.E.узла}: сюда подставляется значение из собранного мира.
// Корни: W — мир (W.R раса, W.E среда, W.EP век, W.D доктрина),
//        Л — люди этой хроники (Л.стар.имя, Л.лет.нужда).
// {Б:W.R.старшие} — то же, но с большой буквы: фраза начинается с дыры.
//
// ⚠ Дыры выдумывать нельзя: имя, которого нет в мире, встанет в текст словом
// «undefined». Список того, что бывает, — saga_weave.js (RACE, ENVS, EPOCH).
// Проверка: node tools/saga_lint.js и вкладка «📜 Хроника» — она красит
// такие кадры красным.
//
// ⚠ Голос — семь правил конструктора (lore/saga_constructor.md §5):
// летописец, а не наблюдатель; кадр = 2–4 коротких предложения; сперва вещь,
// потом её имя; глагол вместо отрицания; никаких выдуманных терминов.
//
// Файл собран из полок: node tools/saga_text_extract.js --write
// ════════════════════════════════════════════════════════════
`;

const тело = ШАПКА + `(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.SagaText = api;
})(typeof window !== 'undefined' ? window : null, function () {
  'use strict';

  // ПОЛКА 1 · ТЕМЫ — о чём хроника. Берётся по состоянию надлома.
  const ТЕМЫ = ${j(ТЕМЫ)};

  // ПОЛКА 2 · ЛЮДИ — нужда, помеха, что скрывает. Нужда НИКОГДА не совпадает
  // с должностью: летописец хочет не «вести свод».
  const НУЖДЫ = ${j(НУЖДЫ)};

  // ПОЛКА 3 · РУЖЬЯ — вещь или привычка, посаженная без объяснения. Стреляет
  // через две главы. Условие («у них есть руки») живёт в saga_kit.js по id.
  const РУЖЬЯ = ${j(РУЖЬЯ)};

  // ПОЛКА 6 · ЦЕНА — груз со склада, которого у мира нет и быть не может.
  const ГРУЗЫ = ${j(ГРУЗЫ)};

  // ПОЛКА 4 · СОБЫТИЯ — по крючкам: ЧУЖОЙ (глава I), УГОВОР (II),
  // ПУСТОЕ (III), ВИРА (V). На крючок 3–4 события, иначе два мира с одним
  // крючком дадут одну сцену.
  const СОБЫТИЯ = ${j(СОБЫТИЯ)};

  return { ТЕМЫ, НУЖДЫ, РУЖЬЯ, ГРУЗЫ, СОБЫТИЯ };
});
`;

if (process.argv.indexOf('--write') >= 0) {
  fs.writeFileSync(path.join(__dirname, '..', 'saga_text.js'), тело);
  console.log('saga_text.js записан, ' + тело.split('\n').length + ' строк');
} else {
  console.log(тело.slice(0, 4000));
  console.log('… (--write чтобы записать)');
}

// Что не выносится и почему — печатаем всегда, чтобы это не забылось.
const дыр = (тело.match(/\{[^}]+\}/g) || []).length;
console.error('\nдыр в тексте: ' + дыр
  + '\nосталось кодом: вечера и расколы (полка 7), кадры и варианты глав —'
  + '\nтам ветвление по флагам, род говорящего и счёт цены.');
