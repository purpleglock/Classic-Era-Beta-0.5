// ДОЗВЁЗДНЫЕ · ПАРТИЯ (правила — lore/precursor_run.md)
//
// Здесь лежит ИГРА, а не приборы. У мира появились три вещи, которых не было:
// конечный срок, ресурс, которого не хватает, и два разных конца.
//
// Модель считается на клиенте, БД сверяет тем же счётом (_precursor_run.sql).
// Ни строчки разметки и ни строчки текста хроники: разметка — в
// precursor_run_ui.js, текст — в пластах (saga_layers.js).
// ════════════════════════════════════════════════════════════
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.PrecursorRun = api;
})(typeof window !== 'undefined' ? window : null, function () {
  'use strict';

  // ── постоянные партии ─────────────────────────────────────
  const СРОК = 12;        // ходов в партии
  const ПРИХОД = 3;       // внимания в начале хода
  const ПОТОЛОК = 5;      // больше внимания не копится
  const ПРЕДЕЛ = 100;     // надлом добрался — срыв
  const ДРЕЙФ = 3;        // мир сам по себе идёт вниз: столько надлома за век
  const КАРА = -100;      // досье Фонда: тут он взыскивает четверть казны

  // ── рука державы ──────────────────────────────────────────
  // `хвост` — не текст для красоты, а поле, которое читает `ход()`.
  // ── рука державы ──────────────────────────────────────────
  // `хвост` — не текст для красоты, а поле, которое читает `век()`.
  //
  // ЦЕНА У ДЕЙСТВИЯ ДВОЙНАЯ, и обе половины настоящие:
  //   `гс`   — деньги казны, по той же шкале, что в `_precursor_commit.sql`
  //            (база + надбавка за уровень мира);
  //   `фонд` — досье Фонда по защите от невмешательства, по шкале
  //            `_precursor_decisions.sql` (+5 за невмешательство, −15 за
  //            контакт, −35 за выкачивание). На −100 Фонд взыскивает четверть
  //            казны — это и есть настоящая цена жадности.
  //
  // ⚠ Влияние — это ВРЕМЯ века, а не ресурс державы. Пока платили только им,
  // партия ничего не стоила: ни денег, ни репутации.
  const РУКА = [
    { id: 'покой', имя: 'НЕ ВМЕШИВАТЬСЯ', цена: 1, гс: 0, гсТир: 0, фонд: 5,
      что: 'Отвести корабли. Век они живут без вас.',
      русло: 0,  надлом: -7,  хвост: 'глухо',
      чем: 'Мир отходит от прошлого вмешательства, и Фонд это записывает в вашу пользу.' },
    { id: 'ритм',  имя: 'ПОМОЧЬ В БЕДЕ',   цена: 2, гс: 60000, гсТир: 20000, фонд: -3,
      что: 'Сбросить еду и лекарства, когда у них мор или голод.',
      русло: 8,  надлом: -5,  хвост: 'беда',
      чем: 'К помощи привыкают: следующая беда обойдётся дороже.' },
    { id: 'слово', имя: 'ОТКРЫТЬ ПРАВДУ',  цена: 2, гс: 90000, гсТир: 30000, фонд: -15,
      что: 'Показать им, кто вы и что лежит у них под ногами.',
      русло: 12, надлом: 5,   хвост: 'ноет',
      чем: 'Узнав, они не забудут: ущерб растёт каждый век до конца срока.' },
    // ⚠ ЧЕТВЁРТАЯ КАРТА — НЕ СТУПЕНЬ. Она зовёт серверный обряд
    // (`_precursor_rite.sql`), а тот необратим: планета вычищается целиком,
    // на вере встаёт клеймо, ихор разом ложится на склад. Поэтому:
    //   `обряд: true` — экран жмёт её через подтверждение и своей дверью
    //   (`precursor_run_rite`), а НЕ через `ступень()`;
    //   `фонд: -80` и `надлом: ПРЕДЕЛ` — здесь только для подписи на карточке:
    //   считает их сервер, партия после этого кончена.
    { id: 'тёмное', имя: 'ВЫКАЧАТЬ ДОСУХА', цена: 1, гс: 0, гсТир: 0, фонд: -80,
      обряд: true,
      что: 'Отдать мир обряду: их израсходуют всех и за одну ночь, а из-под опустевших городов поднимется ихор.',
      русло: 18, надлом: 100, хвост: 'конец',
      чем: 'Планета не восстановится никогда, на вашей вере встанет клеймо — и партия на этом кончится.' },
  ];
  // Цена в ГС считается от уровня мира: чем он выше, тем дороже до него дотянуться.
  const ценаГС = (a, тир) => Math.round((a.гс || 0) + (a.гсТир || 0) * (+тир || 0));
  const рукойId = id => РУКА.find(a => a.id === id) || null;

  // ── чистая партия ─────────────────────────────────────────
  // `надлом0` приходит из якоря мира: мир не начинается здоровым, у него уже
  // есть выскобленное место в записи (precursor_sim.js).
  function завести(civ) {
    const раны = ((civ && civ.anchor && civ.anchor.wounds) || [])
      .filter(w => w.state !== 'изжитый').length;
    return {
      ход: 1, срок: СРОК,
      тир: Math.max(0, +((civ || {}).tier) || 0),   // от него цена в ГС
      внимание: ПРИХОД,
      казна: 0,         // ГС державы: подставляет экран из precursor_get
      фонд: 0,          // досье Фонда: оттуда же
      потрачено: 0,     // сколько ГС ушло за партию — видно в конце
      русло: 20,
      надлом: Math.min(60, 10 + раны * 12),
      ноет: 0,          // сколько «Слов» сказано: столько надлома каждый век
      метка: null,      // хвост прошлого хода: 'беда' | 'злоба' | null
      узел: null,       // где стоит хроника
      флаги: {},        // что игрок уже выбрал: по ним ветвятся узлы и варианты
      решено: false,    // событие этого хода закрыто?
      след: [],         // что игрок делал: строки для летописи партии
      конец: null,      // 'держава' | 'кризис' | 'собой' | null
    };
  }

  const жать = (v, a, b) => v < a ? a : v > b ? b : v;

  // ── можно ли сейчас ───────────────────────────────────────
  // Причина отказа — часть правил, и она одна на кнопку и на подпись под ней.
  function можно(R, actId) {
    if (!R || R.конец) return { ok: false, why: 'партия окончена' };
    const a = рукойId(actId);
    if (!a) return { ok: false, why: 'нет такой ступени' };
    if (R.внимание < a.цена) return { ok: false, why: 'в этом веке уже некогда' };
    const гс = ценаГС(a, R.тир);
    if (гс > 0 && (+R.казна || 0) < гс) {
      return { ok: false, why: 'казна не тянет: нужно ' + гс.toLocaleString('ru-RU') + ' ГС' };
    }
    return { ok: true };
  }

  // ── ступень руки ──────────────────────────────────────────
  function ступень(R, actId) {
    const g = можно(R, actId);
    if (!g.ok) return { ok: false, why: g.why, run: R };
    const a = рукойId(actId);
    // Обряд не проходит ступенью ни на клиенте, ни на сервере: у него своя
    // дверь и подтверждение (_precursor_run_rite.sql §1-2).
    if (a.обряд) return { ok: false, why: 'обряд идёт своей дверью', run: R };
    const N = Object.assign({}, R, { след: R.след.slice() });
    N.внимание -= a.цена;
    const гс = ценаГС(a, N.тир);
    N.казна = Math.max(0, (+N.казна || 0) - гс);
    N.потрачено = (+N.потрачено || 0) + гс;
    N.фонд = Math.max(-300, Math.min(50, (+N.фонд || 0) + (a.фонд || 0)));
    // Фонд взыскал: четверть казны и досье откатывается к −50, не к нулю.
    // Тот же порядок, что в `_pc_rep` (_precursor_decisions.sql).
    if (N.фонд <= КАРА) {
      N.штраф = Math.floor((+N.казна || 0) * 0.25);
      N.казна = Math.max(0, N.казна - N.штраф);
      N.фонд = -50;
    } else { N.штраф = 0; }
    N.русло = жать(N.русло + a.русло, 0, 100);
    N.надлом = жать(N.надлом + a.надлом, 0, ПРЕДЕЛ);
    if (a.хвост === 'ноет') N.ноет += 1;
    if (a.хвост === 'беда' || a.хвост === 'злоба') N.метка = a.хвост;
    N.след.push({ ход: N.ход, что: a.имя });
    return { ok: true, run: срыв(N), act: a };
  }

  // ── решение события ───────────────────────────────────────
  // Вариант хроники приходит из пластов, но платит он тем же внимани­ем и
  // двигает те же две шкалы: второй кассы у события нет.
  function решить(R, вар) {
    if (!R || R.конец) return { ok: false, why: 'партия окончена', run: R };
    if (R.решено) return { ok: false, why: 'в этом веке уже решено', run: R };
    const цена = Math.max(0, +(вар && вар.цена) || 0);
    if (R.внимание < цена) return { ok: false, why: 'не хватает внимания', run: R };
    const N = Object.assign({}, R, { след: R.след.slice() });
    N.внимание -= цена;
    N.русло = жать(N.русло + (+(вар && вар.русло) || 0), 0, 100);
    N.надлом = жать(N.надлом + (+(вар && вар.надлом) || 0), 0, ПРЕДЕЛ);
    N.решено = true;
    N.узел = (вар && вар.go) || N.узел;
    // Флаги выбора ведёт партия: узлы ветвятся по ним, и без них строки вида
    // `f => f.летопись === 'правда'` падают на undefined.
    N.флаги = Object.assign({}, N.флаги, (вар && вар.set) || {});
    N.след.push({ ход: N.ход, что: (вар && вар.имя) || 'решение' });
    return { ok: true, run: срыв(N) };
  }

  // ── закрыть век ───────────────────────────────────────────
  // Часы идут только здесь. Пока игрок не решил событие, век не кончается:
  // иначе партию можно просидеть молча, а это не игра.
  function век(R) {
    if (!R || R.конец) return { ok: false, why: 'партия окончена', run: R };
    if (!R.решено) return { ok: false, why: 'век не решён', run: R };
    const N = Object.assign({}, R, { след: R.след.slice() });
    // ── ход мира ──────────────────────────────────────────
    // Мир идёт сам, и сам по себе он идёт ВНИЗ: непрожитая беда не рассасывается.
    // Без этого «ничего не делать» было выигрышной стратегией — замер
    // (tools/pc_run_probe.js) выводил бездействие в державу.
    N.надлом = жать(N.надлом + ДРЕЙФ + N.ноет * 2 + (N.метка === 'беда' ? 3 : 0), 0, ПРЕДЕЛ);
    N.метка = null;
    if (N.ход >= N.срок) return { ok: true, run: исход(N) };
    N.ход += 1;
    N.внимание = Math.min(ПОТОЛОК, N.внимание + ПРИХОД);
    N.решено = false;
    return { ok: true, run: срыв(N) };
  }

  // ── концы ─────────────────────────────────────────────────
  function срыв(R) {
    if (R.конец) return R;
    if (R.надлом >= ПРЕДЕЛ) { R.конец = 'кризис'; R.почему = 'срыв'; }
    return R;
  }
  function исход(R) {
    const d = R.русло - R.надлом;
    R.конец = d > 15 ? 'держава' : d < -15 ? 'кризис' : 'собой';
    R.почему = 'срок';
    return R;
  }

  // Куда исход впадает в игру — уже написано (precursor_risen.js, недоимка).
  const КОНЦЫ = {
    'держава': ['СОЮЗНИК',
      'Мир встал державой и помнит, кто рядом стоял. Караваны и ихор идут через вас.'],
    'кризис': ['УГРОЗА',
      'Мир вышел к звёздам сломанным. Он уводит население и растёт с уведённого — это жёстче пиратов.'],
    'собой': ['ЧУЖИЕ',
      'Ни соседа, ни беды. Мир идёт своей дорогой и вас в ней не числит.'],
    // Четвёртый конец: партия не доиграна, а обменяна. Ни союзника, ни
    // угрозы — потому что мира больше нет.
    'обмен': ['ОБМЕНЯН',
      'Мира нет. Его отдали обряду и получили ихор — разом, единожды и навсегда. '
      + 'На вере державы стоит клеймо, и его видит вся галактика.'],
  };

  // Куда клонится сейчас — чтобы игрок видел это ДО конца срока, а не после.
  function клон(R) {
    const d = (R.русло || 0) - (R.надлом || 0);
    return d > 15 ? 'держава' : d < -15 ? 'кризис' : 'собой';
  }

  return { СРОК, ПРИХОД, ПОТОЛОК, ПРЕДЕЛ, КАРА, РУКА, КОНЦЫ,
           завести, можно, ступень, решить, век, клон, рукойId, ценаГС };
});
