-- ХРОНИКА · РУКОПИСИ СНЯТЫ С БОРТА  (этап 12, пункт 8)
--
-- «Долгая Вода» и «Восьмой жилы нет» были двумя мирами на всю галактику:
-- кто бы что ни нашёл, читал он одни и те же одиннадцать пристаней. Обе
-- находки уехали в пласты редкими вариантами (saga_layers2.js): счёт без
-- восьмого номера достаётся тем, кто метит мёртвых числом; выскобленный
-- разворот — примерно трети приморских миров с письмом.
--
-- Файлы сняты с загрузки. Остались СЛЕДЫ игроков, которые эти хроники
-- дочитали, и терять их нельзя: дочитанная хроника — это то, что о державе
-- записано в чужой книге, а книга не перестаёт существовать оттого, что мы
-- переписали движок.
--
-- Здесь старые исходы переводятся в новые именами и ложатся в pc_record —
-- ту самую чужую память, по которой новый мир встречает державу
-- (pc_start_attitude). Сами строки precursor_saga не трогаем: перечитать
-- их уже нечем, но и стирать чужое прохождение мы не будем.
--
-- Накат идемпотентный.
-- ════════════════════════════════════════════════════════════

insert into public.pc_record (world, faction_id, seen_as, ending, fate, строка, at)
select r.world, r.faction_id,
       case r.world when 'kailat' then 'пришедшие сверху'
                    when 'kharn'  then 'мягкие, что говорят' end,
       -- Старые исходы были про ОДИН мир и назывались его словами. Переводим
       -- в общие имена: важно не как это называлось, а чем кончилось.
       case r.ending
         when 'вместе'            then 'побратим'
         when 'заплатил-вписано'  then 'долгий_счёт'
         when 'заплатил'          then 'долгий_счёт'
         when 'указал-названо'    then 'своё_имя'
         when 'указал'            then 'немой_век'
         when 'встал-имя'         then 'отпущенные'
         when 'встал'             then 'спящая_вещь'
         -- Кхарн: его исходы жили под своими именами
         when 'число'             then 'своё_имя'
         when 'вира-возможна'     then 'побратим'
         when 'ушли'              then 'спящая_вещь'
         else 'спящая_вещь' end,
       null,
       case r.ending
         when 'вместе'           then 'Сели в ряд и не встали, пока счёт не сошёлся.'
         when 'заплатил-вписано' then 'Заплатили за тех, кто брал, и велели это записать.'
         when 'заплатил'         then 'Заплатили за тех, кто брал, и просили не писать.'
         when 'указал-названо'   then 'Назвали тех, кто брал. Счёт ушёл за горизонт.'
         when 'указал'           then 'Что-то решили за нас и не сказали что.'
         when 'встал-имя'        then 'Приняли взыскание на себя, и доля пришла позже.'
         when 'встал'            then 'Приняли взыскание на себя, и только.'
         else 'Приходили.' end,
       coalesce(r.updated_at, now())
  from public.precursor_saga r
 where r.world in ('kailat', 'kharn') and r.done and r.ending is not null
on conflict (world, faction_id) do nothing;

comment on table public.pc_record is
  'Что мир записал про пришедшую сверху державу. Живёт вечно, читается всеми, '
  'задаёт встречу в новых мирах (pc_start_attitude). Строки kailat/kharn — '
  'наследство рукописных хроник, снятых с борта в этапе 12.';
