// ◈ ПРЕСТОЛ: ЯКОРЬ — ЧЁРНАЯ ЗВЕЗДА.
// ⚠️ ЗАБРАКОВАНЫ ДВЕ ПРЕДЫДУЩИЕ РЕДАКЦИИ, обе по делу:
//   1) мягкая тёмная заливка — говорит на языке слоя туманностей и читается
//      как «подкрашено», а не как «здесь случилась беда»;
//   2) вырез с кольцом карантина и радиальной насечкой — читается как СХЕМА.
//      Пунктир, засечки, ровные лучи — это словарь чертежа, а карта галактики
//      им нигде больше не пользуется, поэтому отметка выглядела наклейкой
//      поверх мира, а не частью мира.
//
// ПРАВИЛО: якорь — это АСТРОНОМИЧЕСКИЙ ОБЪЕКТ, с которым что-то не так, а не
// значок. Никаких пунктиров, засечек и правильных многоугольников. Всё, что
// рисуется, должно объясняться физикой: свет вытеснен, вещество падает внутрь,
// на границе горит кольцо.
//
// СОБРАНО ИЗ ЧЕТЫРЁХ СЛОЁВ (снаружи внутрь):
//   • ВЫТЕСНЕНИЕ — свет вокруг гаснет к центру. В отличие от туманности край
//     не растворяется в никуда, а уплотняется: видно, что тьму сюда СТЯНУЛО.
//   • АККРЕЦИЯ — дуги вещества, падающего внутрь. Наклон у каждой свой,
//     вращаются медленно и с разной скоростью, поэтому рисунок никогда не
//     повторяется и не читается как узор.
//   • ГОРИЗОНТ — чистая чернота. Не серая, не тёмно-красная: чёрная.
//   • КОЛЬЦО — узкая раскалённая кромка ровно по краю горизонта,
//     НЕРАВНОМЕРНОЙ яркости по обходу. Равномерное кольцо — снова чертёж.
//
// ⚠️ РИСУЕТСЯ ПОВЕРХ ЗВЁЗД (вызов после gmmPaintStars). Горизонт обязан
// ГАСИТЬ светило: под звёздами она ложится сверху и вся затея сводится к
// ободку вокруг обычной живой системы.
//
// ⚠️ БЕЗ shadowBlur. Свечение набираем наложением обводок с падающей альфой:
// размытие тени на канвасе считается попиксельно и роняет кадр, а карта с
// ангелом уже однажды легла именно на этом (см. angel-map-lag-detail-cap).
//
// ⚠️ Радиус — в МИРОВЫХ единицах: при среднем расстоянии между звёздами ~200
// соседние якоря сливаются в общее поле, и кризис читается территорией.
// Экранный размер зажат с двух сторон, дуги отключаются на мелком масштабе.
//
// ⚠️ БЕЗ ТУМБЛЕРА И БЕЗ РАЗВЕДКИ, как переплавка и сам ковчег: якоря — это
// полоса здоровья кризиса, прятать её не от кого, а спрятанная за выключенным
// тумблером она бы просто не существовала (см. map-defense-visible-to-all).
function gmmPaintAnchors(ctx, camS) {
  const lst = GM.anchors;
  if (!lst || !lst.length || !GM.systems || !GM.systems.length) return;
  const byId = {};
  lst.forEach(a => { if (a && a.system_id) byId[a.system_id] = a; });
  const mg = 400, u = 1 / camS;
  const t = (typeof performance !== 'undefined' ? performance.now() : Date.now()) / 1000;
  ctx.save();
  ctx.lineCap = 'round';

  GM.systems.forEach(s => {
    const a = byId[s.id]; if (!a) return;
    const X = s.x * camS + GMM.tx, Y = s.y * camS + GMM.ty;
    if (X < -mg || X > GMM.vw + mg || Y < -mg || Y > GMM.vh + mg) return;
    const _scY = s.y * camS + GMM.ty, _dyW = (gmmTY(_scY) - _scY) / camS;
    ctx.save(); ctx.translate(0, _dyW);

    const w = Math.max(1, +a.worlds || 1);
    let R = 150 * (1 + 0.14 * Math.min(4, w - 1));
    R = Math.max(R, 15 * u); R = Math.min(R, 120 * u);
    const Rpx = R * camS;                 // экранный радиус — по нему решаем детальность
    const core = R * 0.30;                // горизонт
    const sq = 0.94;                      // сплюснутость по y, как у всего на карте
    // Сид от координат: у каждой чёрной звезды свой наклон дисков и свой ритм,
    // иначе несколько якорей рядом выглядят штампом.
    const seed = Math.abs(s.x * 0.013 + s.y * 0.007) % 6.283;

    // ── 1. ВЫТЕСНЕНИЕ СВЕТА ────────────────────────────────
    // Две остановки у самого края дают уплотнение вместо мягкого схода в ноль:
    // граница ЧУВСТВУЕТСЯ, но нигде не превращается в линию.
    const g1 = ctx.createRadialGradient(s.x, s.y, core * 0.9, s.x, s.y, R * 1.25);
    g1.addColorStop(0.00, 'rgba(0,0,0,0.95)');
    g1.addColorStop(0.34, 'rgba(6,3,6,0.72)');
    g1.addColorStop(0.72, 'rgba(14,6,10,0.34)');
    g1.addColorStop(1.00, 'rgba(14,6,10,0.00)');
    ctx.fillStyle = g1;
    ctx.beginPath(); ctx.ellipse(s.x, s.y, R * 1.25, R * 1.25 * sq, 0, 0, Math.PI * 2); ctx.fill();

    // ── 2. АККРЕЦИЯ ────────────────────────────────────────
    // Дуги, а не замкнутые эллипсы: замкнутый — орбита, дуга — падение.
    if (Rpx > 9) {
      const arcs = Rpx > 22 ? 5 : 3;
      for (let i = 0; i < arcs; i++) {
        const f = i / arcs;
        const rad = core * 1.25 + (R * 0.62 - core * 1.25) * f;
        const tilt = seed + i * 1.17;                          // свой наклон
        const spin = t * (0.30 - 0.045 * i) + seed + i * 2.1;  // своя скорость
        const span = 1.5 + 1.6 * ((i * 7) % 5) / 5;            // своя длина
        ctx.globalAlpha = 0.34 - 0.045 * i;
        ctx.strokeStyle = i % 2 ? 'rgba(214,74,48,1)' : 'rgba(242,158,96,1)';
        ctx.lineWidth = (2.6 - 0.35 * i) * u;
        ctx.beginPath();
        ctx.ellipse(s.x, s.y, rad, rad * (0.34 + 0.16 * f), tilt, spin, spin + span);
        ctx.stroke();
      }
      ctx.globalAlpha = 1;
    }

    // ── 3. ГОРИЗОНТ ────────────────────────────────────────
    ctx.fillStyle = '#000';
    ctx.beginPath(); ctx.ellipse(s.x, s.y, core, core * sq, 0, 0, Math.PI * 2); ctx.fill();

    // ── 4. КОЛЬЦО ──────────────────────────────────────────
    // Обход сегментами: яркость гуляет по окружности и медленно перетекает.
    // Ровное кольцо одной обводкой — это опять чертёж.
    const SEG = 30;
    for (let i = 0; i < SEG; i++) {
      const a0 = i / SEG * Math.PI * 2, a1 = (i + 1.06) / SEG * Math.PI * 2;
      const heat = 0.34 + 0.66 * Math.pow(
        0.5 + 0.5 * Math.sin(a0 * 2 + t * 0.55 + seed) * Math.sin(a0 * 3 - t * 0.33), 2);
      // три наложения: широкое тусклое → узкое раскалённое. Это и есть свечение.
      ctx.globalAlpha = 0.20 * heat;
      ctx.strokeStyle = 'rgba(214,74,48,1)'; ctx.lineWidth = 5.0 * u;
      ctx.beginPath(); ctx.ellipse(s.x, s.y, core, core * sq, 0, a0, a1); ctx.stroke();
      ctx.globalAlpha = 0.55 * heat;
      ctx.strokeStyle = 'rgba(242,158,96,1)'; ctx.lineWidth = 2.2 * u;
      ctx.beginPath(); ctx.ellipse(s.x, s.y, core, core * sq, 0, a0, a1); ctx.stroke();
      ctx.globalAlpha = 0.85 * heat * heat;
      ctx.strokeStyle = 'rgba(255,236,206,1)'; ctx.lineWidth = 0.9 * u;
      ctx.beginPath(); ctx.ellipse(s.x, s.y, core, core * sq, 0, a0, a1); ctx.stroke();
    }
    ctx.globalAlpha = 1;

    // ── 5. ПОДПИСЬ ─────────────────────────────────────────
    // Число миров — прямым текстом: «звезда почернее» игрок не считает,
    // «7 МИРОВ» считает сразу. Без рамки и без плашки: рамка — снова чертёж.
    if (Rpx > 11) {
      ctx.font = '700 ' + (10.5 * u).toFixed(2) + 'px ui-monospace, "Consolas", monospace';
      ctx.textAlign = 'center'; ctx.textBaseline = 'bottom';
      const lbl = w + (w === 1 ? ' МИР' : (w < 5 ? ' МИРА' : ' МИРОВ'));
      ctx.lineWidth = 3.4 * u; ctx.strokeStyle = 'rgba(4,9,16,0.95)';
      ctx.strokeText(lbl, s.x, s.y - R * 0.92);
      ctx.fillStyle = 'rgba(250,206,160,0.95)';
      ctx.fillText(lbl, s.x, s.y - R * 0.92);
    }

    ctx.restore();
  });
  ctx.restore();
}
