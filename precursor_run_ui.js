// ════════════════════════════════════════════════════════════
// ДОЗВЁЗДНЫЕ · ЭКРАН ПАРТИИ  (правила — lore/precursor_run.md)
//
// ЕДИНСТВЕННЫЙ экран мира. Заменяет пять вкладок карточки (Мир · Донесение ·
// Ступени · Держава · Летопись) и читалку хроники.
//
// Было: приборы, крючки, календарь седмиц, две беды, две летописи и два
// списка решений — десять панелей, ни одного вопроса игроку. Стало три зоны
// и один вопрос в каждый век:
//
//   ВЕРХ    срок (12 меток), внимание, куда клонится исход
//   ЦЕНТР   событие века: кадр, сцена, 2-3 решения с ценой
//   НИЗ     рука державы: четыре ступени, цена и хвост у каждой
//
// Приборы никуда не делись — они свёрнуты в одну строку под сроком и
// раскрываются по «?». На экране их нет: игрок играет, а не читает телеметрию.
//
// Эмодзи запрещены: значки — контурный SVG на currentColor.
// ════════════════════════════════════════════════════════════
(function () {
  'use strict';

  const esc = s => String(s == null ? '' : s).replace(/[&<>"']/g,
    m => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[m]));
  const RUN = () => window.PrecursorRun;

  // ── состояние экрана ──────────────────────────────────────
  const _runs = {};              // ключ мира → партия
  let _подробно = false;         // приборы развёрнуты?
  const key = c => c.system_id + ':' + c.pid;

  const num = v => Math.round(+v || 0).toLocaleString('ru-RU');

  // ══════════════════════════════════════════════════════════
  // ПАРТИЯ ЖИВЁТ НА СЕРВЕРЕ (_precursor_run.sql)
  //
  // Считает шкалы по-прежнему клиент — рисовать по ним экран надо мгновенно.
  // Но ДЕНЬГИ И ДОСЬЕ ФОНДА считает база, и она же хранит партию: до этого
  // ГС списывались понарошку и возвращались по F5.
  //
  // Строка базы (turn/att/flow/wound/…) ложится на поля модели один в один —
  // перевод здесь, в одном месте, чтобы имена не разъезжались по файлу.
  // ══════════════════════════════════════════════════════════
  function изБазы(row, gc, rep) {
    if (!row) return null;
    return {
      ход: +row.turn || 1, срок: RUN().СРОК,
      внимание: +row.att || 0,
      русло: +row.flow || 0, надлом: +row.wound || 0,
      ноет: +row.ache || 0, метка: row.mark || null,
      узел: row.node || null, флаги: row.flags || {},
      решено: !!row.decided, тир: +row.tier || 0,
      казна: +gc || 0, фонд: +rep || 0,
      потрачено: +row.spent || 0, штраф: +row.fined || 0,
      след: (row.trail || []).map(x => ({ ход: +x['век'] || 0, что: имяШага(x['что']) })),
      конец: row.ending || null, почему: row.why || null,
    };
  }
  // В базе лежит id ступени ('ритм'), а в летописи партии игрок должен читать
  // то же имя, что на кнопке.
  function имяШага(id) {
    const a = RUN().рукойId && RUN().рукойId(id);
    return a ? a.имя : (id || 'решение');
  }

  const _ждём = {};    // ключ мира → запрос уже ушёл (второго не шлём)
  function run(c) {
    const k = key(c);
    if (!_runs[k]) {
      if (RUN()) _runs[k] = RUN().завести(c);           // заготовка на один кадр
      грузить(c);
    }
    return _runs[k] || null;
  }
  async function грузить(c) {
    const k = key(c);
    if (_ждём[k] || typeof ecRpc !== 'function') return;
    _ждём[k] = true;
    try {
      const r = await ecRpc('precursor_run_get', { p_system_id: c.system_id, p_pid: +c.pid });
      if (r && r.ok && r.run) {
        // Свежая партия ещё не заведена в базе — считаем её заготовкой, но
        // казну и досье берём настоящие: на них смотрит цена действий.
        _runs[k] = изБазы(r.fresh
          ? Object.assign({ turn: 1, att: RUN().ПРИХОД, decided: false }, r.run)
          : r.run, r.gc, r.rep);
        перерисовать();
      }
    } catch (e) { console.warn('партия: не читается', e); }
    _ждём[k] = false;
  }
  // Ответ двери кладём как есть: сервер — источник правды по деньгам и Фонду.
  function принять(c, r) {
    if (!r) return false;
    if (r.ok === false) { ругнуться(r.why); return false; }
    const было = _runs[key(c)] || {};
    _runs[key(c)] = изБазы(r.run,
      r.gc != null ? r.gc : было.казна,
      r.rep != null ? r.rep : было.фонд);
    if (r.fine) toastОк(`Фонд взыскал ${num(r.fine)} ГС`, 'err');
    else if (r.cost) toastОк(`Списано ${num(r.cost)} ГС`);
    перерисовать();
    return true;
  }
  function toastОк(t, k) { if (typeof toast === 'function') toast(t, k || 'ok'); }

  // ══════════════════════════════════════════════════════════
  // СОБЫТИЕ ВЕКА · берётся из хроники, а не пишется заново
  // ══════════════════════════════════════════════════════════
  // Хроника подаётся как событие хода: кадр сверху, её варианты — решения
  // века. Отдельного экрана, выдержек и «далее» у неё больше нет.
  //
  // Вес варианта пласты объявляют сами: `вес` от −2 до +2 — это чаша хроники,
  // и придумывать поверх неё второй счёт незачем. Партия его только переводит
  // в свои две шкалы. `tail` — последствие, написанное там же: показываем его
  // ДО нажатия, иначе выбор снова станет угадыванием.
  //
  // ⚠ Переход у варианта называется `to`, а не `go` (`go` — у узлов чтения).
  function варианты(n, флаги) {
    const F = флаги || {};
    // `if` у варианта — не украшение: он прячет то, что этому игроку уже
    // недоступно. Индекс держим ИСХОДНЫЙ, иначе решение уедет не в тот узел.
    const asks = ((n && n.ask) || [])
      .map((a, i) => ({ a, i }))
      .filter(x => !x.a.if || x.a.if(F))
      .map(x => Object.assign({}, x.a, { _i: x.i }));
    return asks.map((a) => {
      const i = a._i;
      const w = +a['вес'] || 0;
      const платный = !!(a.cost && ((a.cost.груз && a.cost.груз.n) || a.cost.срок));
      return {
        i, имя: a.t, go: a.to || a.go, хвост: a.tail || '', set: a.set || null,
        цена:   платный ? 1 : (w > 0 ? 1 : 0),
        русло:  w * 6 + (платный ? 6 : 0),
        надлом: -w * 3,
      };
    });
  }

  // Сдвиг шкалы словами. ЕДИНСТВЕННОЕ место, где число становится подписью:
  // пока их было два, «русло» и «надлом» протекли на экран под кнопками, хотя
  // заголовки уже были переименованы.
  // Минус — типографский (−), как в «ВЛИЯНИЕ −1»: дефис рядом с ним в одной
  // строке выглядит опечаткой.
  const сдвигТxt = (имя, v) => имя + ' ' + (v > 0 ? '+' + v : '−' + Math.abs(v));

  // ── сцена века ────────────────────────────────────────────
  // Узлы хроники сплошь «читать дальше»: у пролога нет ни одного решения, за
  // ним ещё два таких же. Век, который кончается кнопкой «далее», — это не
  // ход, это перелистывание, и именно из-за него хронику назвали неиграбельной.
  //
  // Поэтому век идёт по цепочке `go` ДО ПЕРВОГО УЗЛА С РЕШЕНИЯМИ.
  //
  // ⚠ РЕЗАТЬ МОЖНО ТОЛЬКО ПО УЗЛАМ, НИКОГДА ВНУТРИ УЗЛА.
  // Здесь стоял обрез «последние семь строк». Он срезал у сцены НАЧАЛО:
  // от главы «Отданное не в той форме» пропадали ящик, разобранный за день,
  // приход выяснять долг и сбившийся счёт Ваарха — оставался хвост про порох
  // и поручника. Читалось это как бред: реплики из разных сцен подряд, без
  // того, что их объясняет.
  //
  // Узел = сцена. Показываем ЦЕЛИКОМ последнюю содержательную сцену и всё,
  // что за ней (обычно короткая подводка к решению). Что прочитано раньше —
  // прошлые века, и их место в летописи, а не в этом кадре.
  function сцена(c) {
    const W = мир(c);
    if (!W || !W.NODES) return null;
    const R = run(c);
    const F = (R && R.флаги) || {};
    let id = (R && R.узел) || W.first;
    const блоки = [];
    let глава = null, n = null;
    for (let шаг = 0; шаг < 12; шаг++) {
      n = W.NODES[id];
      if (!n) break;
      if (n.ch) глава = n.ch;      // имя даёт та глава, в которой мы СЕЙЧАС
      const строки = [];
      (n.t || []).forEach(x => {
        const s = typeof x === 'function' ? x(F) : x;
        // `undefined` или пустая строка в сборке — дыра в полке (saga_kit.js).
        // Показать её игроку нельзя, молчать о ней тоже.
        if (s == null || !String(s).trim()) return;
        if (/undefined/.test(String(s))) {
          console.warn('партия: дыра в сборке узла', id, s); return;
        }
        строки.push(String(s));
      });
      if (строки.length) блоки.push({ id, строки, who: n.who });
      if ((n.ask || []).length || n.end) break;
      if (!n.go) break;
      id = n.go;
    }
    // Последняя сцена — последний блок, где есть о чём читать (3 строки и
    // больше), плюс всё после неё. Внутри блока не режем.
    let с = 0;
    for (let i = блоки.length - 1; i >= 0; i--) {
      if (блоки[i].строки.length >= 3) { с = i; break; }
    }
    const взятые = блоки.slice(с);
    const текст = [].concat.apply([], взятые.map(б => б.строки));
    const кто = (взятые[0] && взятые[0].who) || (n && n.who) || null;
    return n ? { n, id, текст, глава, кто } : null;
  }
  // ⚠ Имя из `who` в шапку НЕ ставим. `who` — тот, о КОМ сцена, а не тот, кто
  // говорит: в главе I стоит `who: 'стар'`, а Ваарх в самом тексте идёт
  // третьим лицом («Ваарх считает вслух и сбивается»). Подписать его
  // рассказчиком значит соврать в шапке. Людей называет сам текст.
  function мир(c) {
    const PS = window.PrecursorSaga;
    if (!PS || !PS.setWorld || !PS.setWorld(sagaKey(c))) return null;
    return PS.world || null;
  }
  function sagaKey(c) {
    return window.SagaWeave && SagaWeave.key ? SagaWeave.key(c) : ('civ:' + c.system_id + ':' + c.pid);
  }

  // ══════════════════════════════════════════════════════════
  // ЗОНА 1 · СРОК, ВНИМАНИЕ, КУДА КЛОНИТСЯ
  // ══════════════════════════════════════════════════════════
  // ⚠ ИМЕНА. «Русло», «Надлом», «Внимание» — слова из лора: игрок читает их и
  // не знает, что они для него значат. На экране стоят обычные слова, за
  // которыми видно действие. Внутри модели ключи прежние — переименовывать их
  // значит ломать сверку с сервером.
  //
  //   русло  → РАЗВИТИЕ  (докуда мир дорос)
  //   надлом → УЩЕРБ     (сколько мы ему наломали)
  //   внимание → ВЛИЯНИЕ (сколько ходов державы влезает в век)
  const КЛОН_НМ = {
    'держава': ['ПРОГНОЗ: СОЮЗНИК', 'ok'],
    'кризис':  ['ПРОГНОЗ: УГРОЗА', 'bad'],
    'собой':   ['ПРОГНОЗ: ЧУЖИЕ', 'mid'],
  };

  // ── скан мира: круговая развёртка ─────────────────────────
  // Две дуги на общем круге: развитие идёт по часовой, ущерб — навстречу.
  // Смысл читается без цифр: чья дуга длиннее, туда мир и уедет. Внутри —
  // век и прогноз. Призрачная дуга (`ghost`) показывает примерку действия.
  const ДУГА = (r, доля, кл) => {
    const L = 2 * Math.PI * r;
    return `<circle class="${кл}" cx="60" cy="60" r="${r}" fill="none" stroke-width="7"
      stroke-dasharray="${(L * Math.max(0, Math.min(1, доля))).toFixed(1)} ${L.toFixed(1)}"
      stroke-linecap="butt" />`;
  };
  function скан(R) {
    const [кт, тон] = КЛОН_НМ[RUN().клон(R)] || КЛОН_НМ['собой'];
    return `<svg class="pcr-скан" viewBox="0 0 120 120" aria-hidden="true">
      <circle class="pcr-скан-фон" cx="60" cy="60" r="52" fill="none" stroke-width="7"/>
      <circle class="pcr-скан-фон" cx="60" cy="60" r="41" fill="none" stroke-width="7"/>
      <g transform="rotate(-90 60 60)">
        ${ДУГА(52, R.русло / 100, 'pcr-дуга-разв')}
        ${ДУГА(52, 0, 'pcr-дуга-разв-п')}
      </g>
      <g transform="rotate(-90 60 60) scale(1,-1) translate(0,-120)">
        ${ДУГА(41, R.надлом / 100, 'pcr-дуга-ущерб')}
        ${ДУГА(41, 0, 'pcr-дуга-ущерб-п')}
      </g>
      <text class="pcr-скан-век" x="60" y="56">${R.ход}/${R.срок}</text>
      <text class="pcr-скан-под pcr-${тон}" x="60" y="72">${esc(кт.split(': ')[1] || '')}</text>
    </svg>`;
  }

  function шапка(c, R) {
    const метки = Array.from({ length: R.срок }, (_, i) =>
      `<i class="pcr-t${i + 1 < R.ход ? ' был' : i + 1 === R.ход ? ' тут' : ''}"></i>`).join('');
    const очки = Array.from({ length: RUN().ПОТОЛОК }, (_, i) =>
      `<i class="pcr-a${i < R.внимание ? ' есть' : ''}"></i>`).join('');
    const [кт, тон] = КЛОН_НМ[RUN().клон(R)] || КЛОН_НМ['собой'];
    const шкала = (кл, нм, v, что) => `<div class="pcr-ш pcr-ш-${кл}">
      <div class="pcr-ш-hd"><b>${нм}</b><u data-ш="${кл}">${v}</u></div>
      <div class="pcr-ш-п"><i style="width:${v}%"></i><s data-п="${кл}" style="left:${v}%;width:0"></s></div>
      <div class="pcr-ш-что">${esc(что)}</div>
    </div>`;
    return `<div class="pcr-hud pcr-гр">
      ${скан(R)}
      <div class="pcr-hud-к">
        <div class="pcr-строка">
          <span class="pcr-мет">СРОК</span><span class="pcr-срок-л">${метки}</span>
          <span class="pcr-клон pcr-${тон}">${esc(кт)}</span>
          <button class="pcr-q" type="button" title="Полные показатели мира"
            onclick="event.stopPropagation();pcrПодробно()">${_подробно ? '×' : 'i'}</button>
        </div>
        <div class="pcr-строка">
          <span class="pcr-мет">ВЛИЯНИЕ</span><span class="pcr-вним-л">${очки}</span>
          <span class="pcr-вним-что">хватает на ${R.внимание} ${
            R.внимание === 1 ? 'шаг' : R.внимание < 5 ? 'шага' : 'шагов'} в этом веке</span>
        </div>
        ${держава(R)}
        <div class="pcr-шкалы">
          ${шкала('разв', 'РАЗВИТИЕ', R.русло, 'докуда мир дорос сам')}
          ${шкала('ущерб', 'УЩЕРБ', R.надлом, 'что мы ему наломали')}
        </div>
      </div>
    </div>
    ${_подробно ? приборы(c) : ''}`;
  }

  // ── ЧЕМ ПЛАТИТ ДЕРЖАВА ────────────────────────────────────
  // Влияние — это время века. Настоящие затраты другие, и до сих пор их на
  // экране не было вовсе: КАЗНА (ГС по шкале `_precursor_commit.sql`) и ДОСЬЕ
  // ФОНДА (`faction_foundation.rep`). Досье — не украшение: на −100 Фонд
  // взыскивает четверть казны и откатывает счёт к −50, а не к нулю.
  function держава(R) {
    const К = RUN().КАРА;
    const близко = R.фонд <= К * 0.6;          // −60 и ниже: пора смотреть
    const доля = Math.max(0, Math.min(1, R.фонд / К));   // 0 чисто … 1 кара
    return `<div class="pcr-строка pcr-держава">
      <span class="pcr-мет">КАЗНА</span>
      <span class="pcr-казна">${num(R.казна)} ГС${
        R.потрачено ? ` <em>за партию −${num(R.потрачено)}</em>` : ''}</span>
      <span class="pcr-мет">ДОСЬЕ ФОНДА</span>
      <span class="pcr-фонд${близко ? ' горит' : ''}" title="На ${К} Фонд взыскивает четверть казны">
        <i style="width:${(доля * 100).toFixed(0)}%"></i><b>${R.фонд > 0 ? '+' : ''}${R.фонд}</b>
      </span>
      ${R.штраф ? `<span class="pcr-штраф">Фонд взыскал ${num(R.штраф)} ГС</span>` : ''}
    </div>`;
  }

  // Приборы — свёрнуты. Это справка о мире, а не поле игры, и места на
  // экране им не отдаём.
  function приборы(c) {
    const D = window.PrecursorDossier;
    const p = D && D.parts ? D.parts(c) : null;
    return `<div class="pcr-приборы">${p ? p['приборы'] + p['летопись']
      : '<div class="pcr-пусто">Показателей по этому миру ещё нет.</div>'}</div>`;
  }

  // ══════════════════════════════════════════════════════════
  // ЗОНА 2 · СОБЫТИЕ ВЕКА
  // ══════════════════════════════════════════════════════════
  function событие(c, R) {
    const сц = сцена(c);
    const n = сц && сц.n;
    if (!n) {
      return `<div class="pcr-сцена pcr-гр pcr-пусто">В этом веке ничего не случилось.
        <button class="hp-vn-btn" type="button"
          onclick="event.stopPropagation();pcrРешить(-1)">Прожить век молча</button></div>`;
    }
    const вар = варианты(n, R.флаги);
    const текст = сц.текст.map(x => `<p>${esc(x)}</p>`).join('');
    const кадр = фон(c, n);

    const кнопки = R.решено
      ? `<div class="pcr-решено">Решение века записано.</div>`
      : вар.length
        ? вар.map(v => `<button class="pcr-вар pcr-гр" type="button"
            ${R.внимание < v.цена ? 'disabled' : ''}
            onmouseenter="pcrПримерка(${v.русло},${v.надлом})" onmouseleave="pcrПримерка(0,0)"
            onfocus="pcrПримерка(${v.русло},${v.надлом})" onblur="pcrПримерка(0,0)"
            onclick="event.stopPropagation();pcrРешить(${v.i})">
            <span class="pcr-вар-т">${esc(v.имя)}</span>
            <span class="pcr-вар-ц">${v.цена ? 'ВЛИЯНИЕ −' + v.цена : 'даром'}${
              v.русло ? ' · ' + сдвигТxt('развитие', v.русло) : ''}${
              v.надлом ? ' · ' + сдвигТxt('ущерб', v.надлом) : ''}</span>
            ${v.хвост ? `<span class="pcr-вар-хвост">${esc(v.хвост)}</span>` : ''}
          </button>`).join('')
        : `<button class="pcr-вар pcr-гр" type="button"
            onclick="event.stopPropagation();pcrРешить(-1)">
            <span class="pcr-вар-т">Смотреть, что будет</span>
            <span class="pcr-вар-ц">даром</span></button>`;

    return `<div class="pcr-сцена pcr-гр"${кадр ? ` style="background-image:url('${кадр}')"` : ''}>
      ${сц.глава ? `<div class="pcr-глава">${esc(сц.глава)}</div>` : ''}
      <div class="pcr-текст">${текст}</div>
      <div class="pcr-вары">${кнопки}</div>
    </div>`;
  }
  function фон(c, n) {
    try {
      const PS = window.PrecursorSaga;
      if (!window.PcArt || !PS || !PS.world) return null;
      return PcArt.bg(PS.world.id, (PS.S && PS.S.node) || '')
        || PcArt.pick(PS.world.race, n.ep || 'E8', (PS.S && PS.S.node) || '') || null;
    } catch (e) { return null; }
  }

  // ══════════════════════════════════════════════════════════
  // ЗОНА 3 · РУКА ДЕРЖАВЫ
  // ══════════════════════════════════════════════════════════
  function рука(c, R) {
    const карты = RUN().РУКА.map(a => {
      const g = RUN().можно(R, a.id);
      // Обряд необратим, поэтому и на карточке он не притворяется ступенью:
      // сдвиг шкал ему не пишем (мира после него нет — двигать нечего),
      // клик идёт в свою дверь через подтверждение.
      const сдвиг = a.обряд ? 'мир кончится' : [
        a.русло ? сдвигТxt('развитие', a.русло) : '',
        a.надлом ? сдвигТxt('ущерб', a.надлом) : '',
      ].filter(Boolean).join(' · ');
      return `<button class="pcr-карта pcr-гр${a.обряд ? ' обряд' : ''}${g.ok ? '' : ' нельзя'}" type="button"
        ${g.ok ? '' : 'disabled'} onclick="event.stopPropagation();${
          a.обряд ? 'pcrОбряд()' : `pcrСтупень('${a.id}')`}"
        onmouseenter="pcrПримерка(${a.русло},${a.надлом})" onmouseleave="pcrПримерка(0,0)"
        onfocus="pcrПримерка(${a.русло},${a.надлом})" onblur="pcrПримерка(0,0)">
        <span class="pcr-карта-hd"><b>${esc(a.имя)}</b><i>${a.цена}</i></span>
        <span class="pcr-карта-что">${esc(a.что)}</span>
        <span class="pcr-карта-сдвиг">${esc(сдвиг)}</span>
        <span class="pcr-карта-цена">${(() => {
          const гс = RUN().ценаГС(a, R.тир);
          const ч = [];
          // «Казне даром» про обряд — ложь: он бесплатен ровно так же, как
          // бесплатен поджог. Платят верой, и это надо читать на кнопке.
          if (a.обряд) return esc(`клеймо на вере · Фонд −${Math.abs(a.фонд)}`);
          if (гс) ч.push(num(гс) + ' ГС');
          if (a.фонд) ч.push('Фонд ' + (a.фонд > 0 ? '+' : '−') + Math.abs(a.фонд));
          return ч.length ? esc(ч.join(' · ')) : 'казне даром';
        })()}</span>
        <span class="pcr-карта-хвост">${esc(a.чем)}</span>
        ${g.ok ? '' : `<span class="pcr-карта-нет">${esc(g.why)}</span>`}
      </button>`;
    }).join('');
    const можноВек = R.решено;
    return `<div class="pcr-рука">${карты}</div>
      <button class="pcr-век pcr-гр${можноВек ? '' : ' нельзя'}" type="button" ${можноВек ? '' : 'disabled'}
        onclick="event.stopPropagation();pcrВек()">${
        можноВек ? (R.ход >= R.срок ? 'Закрыть партию' : 'Прожить век →')
                 : 'Сперва решите событие века'}</button>`;
  }

  // ══════════════════════════════════════════════════════════
  // КОНЕЦ ПАРТИИ
  // ══════════════════════════════════════════════════════════
  function конец(c, R) {
    const [имя, txt] = RUN().КОНЦЫ[R.конец] || ['—', ''];
    return `<div class="pcr-конец pcr-гр pcr-конец-${R.конец}">
      <div class="pcr-конец-нм">${esc(имя)}</div>
      <div class="pcr-конец-txt">${esc(txt)}</div>
      <div class="pcr-конец-счёт">${R.конец === 'обмен'
        // Шкалы обменянного мира считать не по чему: его нет. Счёт тут один —
        // на каком веку его отдали.
        ? `Отдан обряду на ${R.ход}-м веку из ${R.срок}`
        : `Русло ${R.русло} · Надлом ${R.надлом} · веков прожито ${
            R.почему === 'срыв' ? R.ход : R.срок}`}</div>
      <div class="pcr-конец-след">${R.след.slice(-8).reverse().map(s =>
        `<span>Век ${s.ход}: ${esc(s.что)}</span>`).join('')}</div>
    </div>`;
  }

  // ══════════════════════════════════════════════════════════
  // СБОРКА
  // ══════════════════════════════════════════════════════════
  function экран(c) {
    if (!RUN()) return '';
    const R = run(c);
    if (!R) return '';
    const голова = `<button class="hp-vn-btn hp-vn-back" type="button"
        onclick="event.stopPropagation();heroVNTamaBack()">← к списку</button>
      <div class="pcr-имя">${esc(c.self_name || '?')}
        <span>${esc(c.planet_name || '')} · система ${esc(c.system_name || c.system_id)}</span></div>`;
    if (R.конец) return `<div class="pcr">${голова}${конец(c, R)}</div>`;
    return `<div class="pcr">${голова}${шапка(c, R)}${событие(c, R)}${рука(c, R)}</div>`;
  }

  // ── обработчики ───────────────────────────────────────────
  // Открытый мир держит карточка (`_pcOpenCiv` в precursor_ui.js) — своего
  // курсора экран не заводит: два курсора однажды разойдутся.
  // ⚠ `_pcOpenCiv` и `_pcState` объявлены через `let` в precursor_ui.js:
  // такие имена видны другим файлам по имени, но НЕ лежат на window. Отсюда
  // голые идентификаторы под typeof, а не `window.*` — иначе тут всегда null.
  const тек = () => {
    if (typeof _pcOpenCiv === 'undefined' || typeof _pcState === 'undefined') return null;
    if (!_pcOpenCiv || !_pcState) return null;
    return (_pcState.civs || []).find(
      x => x.system_id === _pcOpenCiv.s && +x.pid === +_pcOpenCiv.p) || null;
  };

  function перерисовать() {
    if (typeof heroVNTamaRefresh === 'function') heroVNTamaRefresh();
  }
  function ругнуться(why) {
    if (typeof toast === 'function') toast(why || 'Нельзя', 'err');
  }

  window.pcrПодробно = function () { _подробно = !_подробно; перерисовать(); };

  // ── ПРИМЕРКА ──────────────────────────────────────────────
  // Навёл на действие — видно, КУДА уедут шкалы, до нажатия. Без этого цена
  // действия остаётся строчкой цифр, которую игрок обязан считать в уме.
  //
  // Рисуем прямо в DOM, без перерисовки экрана: перерисовка снимет наведение,
  // мышь наведётся снова, и получится мигающий круг.
  window.pcrПримерка = function (русло, надлом) {
    const R0 = тек() && run(тек());
    if (!R0) return;
    const пара = [['разв', +русло || 0, R0.русло], ['ущерб', +надлом || 0, R0.надлом]];
    пара.forEach(([кл, d, было]) => {
      const стало = Math.max(0, Math.min(100, было + d));
      const g = document.querySelector(`[data-п="${кл}"]`);
      if (g) {
        g.style.left = Math.min(было, стало) + '%';
        g.style.width = Math.abs(стало - было) + '%';
        g.className = d < 0 ? 'вниз' : '';
      }
      const n = document.querySelector(`[data-ш="${кл}"]`);
      if (n) {
        n.textContent = d ? `${было} → ${стало}` : String(было);
        n.classList.toggle('примерка', !!d);
      }
      const дуга = document.querySelector(`.pcr-дуга-${кл === 'разв' ? 'разв' : 'ущерб'}-п`);
      if (дуга) {
        const r = кл === 'разв' ? 52 : 41, L = 2 * Math.PI * r;
        const от = Math.min(было, стало) / 100, до = Math.max(было, стало) / 100;
        дуга.setAttribute('stroke-dasharray', `0 ${(L * от).toFixed(1)} ${(L * (до - от)).toFixed(1)} ${L.toFixed(1)}`);
        дуга.classList.toggle('вниз', d < 0);
      }
    });
  };

  // Все три двери — серверные (_precursor_run.sql). Клиент НЕ считает ни ГС,
  // ни досье Фонда: он только показывает то, что вернула база. Отказ («казна
  // не тянет», «в этом веке уже некогда») тоже приходит оттуда — придумывать
  // его здесь значит однажды соврать кнопкой.
  window.pcrСтупень = async function (id) {
    const c = тек(); if (!c) return;
    const R = run(c);
    const g = RUN().можно(R, id);        // быстрая проверка, чтобы не гонять зря
    if (!g.ok) return ругнуться(g.why);
    if (typeof ecRpc !== 'function') return ругнуться('нет связи');
    try {
      принять(c, await ecRpc('precursor_run_act', {
        p_system_id: c.system_id, p_pid: +c.pid, p_act: id }));
    } catch (e) { ругнуться(((e && e.message) || e) + ''); }
  };

  // ── ОБРЯД ─────────────────────────────────────────────────
  // Единственное действие партии, которое НЕЛЬЗЯ отдать обычной кнопке хода:
  // на сервере оно вычищает планету насовсем (status='dead', pop=0), ставит
  // клеймо на веру и оглашает это всей галактике. Поэтому — подтверждение и
  // своя дверь `precursor_run_rite`, а не `precursor_run_act`.
  //
  // Текст подтверждения — тот же, что на карточке мира (PC_CONFIRM.rite в
  // precursor_ui.js), плюс то, что верно только здесь: партия кончится.
  const ОБРЯД_СПРОС =
    'Отдать этот мир обряду? Их не победят и не увезут — их израсходуют, всех и '
    + 'за одну ночь, а из-под опустевших городов поднимется ихор. Планета не '
    + 'восстановится никогда. На вашей вере встанет клеймо, которое не снимается '
    + 'ничем и которое увидит вся галактика.\n\nПартия на этом мире закончится.';

  window.pcrОбряд = async function () {
    const c = тек(); if (!c) return;
    const R = run(c);
    const g = RUN().можно(R, 'тёмное');
    if (!g.ok) return ругнуться(g.why);
    if (typeof ecRpc !== 'function') return ругнуться('нет связи');
    if (!confirm(ОБРЯД_СПРОС)) return;
    try {
      const r = await ecRpc('precursor_run_rite', {
        p_system_id: c.system_id, p_pid: +c.pid });
      if (принять(c, r)) {
        // Мир вычищен, ихор лёг на склад — `перерисовать()` внутри `принять()`
        // перечитывает `precursor_get`, поэтому список и остатки не врут.
        toastОк(r.txt || `Обряд служён. Ихора получено: ${r.ichor}`, 'err');
      }
    } catch (e) { ругнуться(((e && e.message) || e) + ''); }
  };

  window.pcrРешить = async function (i) {
    const c = тек(); if (!c) return;
    const R = run(c);
    if (typeof ecRpc !== 'function') return ругнуться('нет связи');
    let узел = null, вес = 0, цена = 0, флаги = null, имя = 'век прожит молча';
    if (i >= 0) {
      const сц = сцена(c);
      const v = сц && варианты(сц.n, R.флаги).find(x => x.i === i);
      if (!v) return;
      // Вес отдаём ИСХОДНЫЙ (−2..+2, поле `вес` пласта): в свои шкалы его
      // переводит сервер, и второй перевод на клиенте однажды разъедется.
      const сырой = ((сц.n.ask || [])[i] || {});
      узел = v.go || сц.id; вес = +сырой['вес'] || 0; цена = v.цена;
      флаги = v.set || null; имя = v.имя;
    } else {
      const сц0 = сцена(c);
      узел = (сц0 && сц0.n && сц0.n.go) || null;
      вес = -1;                          // прожитый молча век мир не улучшает
    }
    try {
      принять(c, await ecRpc('precursor_run_pick', {
        p_system_id: c.system_id, p_pid: +c.pid, p_node: узел || '',
        p_weight: вес, p_att: цена, p_flags: флаги || {}, p_name: имя }));
    } catch (e) { ругнуться(((e && e.message) || e) + ''); }
  };

  window.pcrВек = async function () {
    const c = тек(); if (!c) return;
    if (typeof ecRpc !== 'function') return ругнуться('нет связи');
    try {
      const r = await ecRpc('precursor_run_turn', {
        p_system_id: c.system_id, p_pid: +c.pid });
      if (принять(c, r) && r.run && r.run.ending) {
        toastОк(r.run.ending === 'держава' ? 'Партия окончена: союзник'
              : r.run.ending === 'кризис' ? 'Партия окончена: угроза'
              : 'Партия окончена: остались собой',
              r.run.ending === 'кризис' ? 'err' : 'ok');
      }
    } catch (e) { ругнуться(((e && e.message) || e) + ''); }
  };

  // `конченная` нужна карточке (precursor_ui.js): мёртвый мир остаётся на
  // экране партии, только если партия по нему ЗАКРЫТА исходом. Заготовка на
  // один кадр исхода не имеет, поэтому до загрузки из базы вернётся false —
  // а `грузить()` следом перерисует карточку уже с настоящим исходом.
  window.PrecursorRunUI = {
    экран, run,
    есть: c => !!run(c),
    конченная: c => { const R = run(c); return !!(R && R.конец); },
  };
})();
