/* ════════════════════════════════════════════════════════════
 * «ПРЕСТОЛ» — СПРАЙТ. Процедурный ветхозаветный ангел.
 * ────────────────────────────────────────────────────────────
 * ПОЧЕМУ НЕ КАРТИНКА. Все корабли на доске — кэшированный офскрин: нарисовали
 * раз, дальше только вертим. Ангелу это не подходит по сути: у него нет позы.
 * Крылья бьют не в такт, кольца идут навстречу друг другу, глаза моргают
 * вразнобой и все вместе смотрят на того, кого он сейчас убивает. Любой
 * запечённый кадр это убивает — поэтому здесь всё считается каждый кадр.
 *
 * ЧТО ИМЕННО РИСУЕМ (и почему так, а не «ангелочек с крылышками»):
 *   • ОФАНИМ — колёса в колёсах, усеянные глазами. Два кольца в разных
 *     наклонах, идут навстречу: получается не вращение, а «глаз не выходит
 *     из тебя», сколько ни поворачивай.
 *   • СЕРАФИМ — шесть крыл тремя парами. Верхняя пара закрывает лик, нижняя
 *     закрывает ноги, средняя — та, которой летают. Они и бьют в разном такте.
 *   • НИМБ — не кружок над головой, а наклонный обод под углом к плоскости
 *     доски, с бегущим по нему блеском.
 *   • ЛИКА НЕТ. Внутри столб света и пустота. Это сознательно: как только у
 *     него появляется лицо, он перестаёт быть страшным и становится персонажем.
 *
 * ЦВЕТ. Тон стороны (свой/союзный/чужой) уходит ТОЛЬКО в дальнее свечение.
 * Само тело всегда кость и золото: ангел не принадлежит стороне, он ей
 * временно попутчик.
 *
 * ЖИВАЯ ПОЗА — ДА, ПОЛНАЯ ПОДРОБНОСТЬ — НЕ ВЕЗДЕ. Считать позу каждый кадр
 * дёшево: это десяток синусов. Дорого — СЛОИ, которые под эту позу рисуются.
 * Поэтому экономят не на движении, а на подробности: см. angelDetail и
 * opt.detail — вызывающий вправе поставить потолок ступени под свой экран.
 *
 * ЗАВИСИМОСТИ: ничего. Чистый canvas 2D, наружу:
 *   angelDraw(ctx, opt)    — нарисовать в точке (opt.detail — потолок ступени)
 *   angelWantsFrames()     — доске: держи rAF живым, пока он на поле
 *   angelHit(id)           — вспышка нимба на попадании (урона нет)
 * ════════════════════════════════════════════════════════════ */

var ANGEL = {
  t0: (typeof performance !== 'undefined' ? performance.now() : Date.now()),
  live: 0,          // сколько ангелов нарисовали в последнем кадре
  hits: {},         // id → время последней вспышки
  seen: {},         // id → прошлый счётчик попаданий (ловим приращение)
  eyes: null,       // раскладка глаз, считается один раз
};

/* ── КАЧЕСТВО РИСОВКИ ───────────────────────────────────────
 * ПОЧЕМУ ЭТО ЗДЕСЬ. Спрайт считается КАЖДЫЙ кадр и целиком: два колеса,
 * 28 глаз, 16 перьев. В первой версии на каждый глаз каждый кадр заводился
 * свой createRadialGradient (радужка) плюс 12 штрихов волокон, а на каждое
 * перо — свой createLinearGradient. Это под сотню новых объектов градиента
 * в кадр на один борт: на десктопе незаметно, на телефоне доска садится.
 *
 * ДВА ЛЕКАРСТВА, оба без потери облика:
 *   1) КЭШ ГРАДИЕНТОВ. Градиент зависит от немногих чисел (длина пера, радиус,
 *      направление взгляда). Квантуем эти числа и держим готовый объект —
 *      глазу разница в 1/32 радиана не видна, движку она стоит всего.
 *   2) БЕРЕЖЛИВЫЙ РЕЖИМ. На телефоне снимаются только те слои, которых на
 *      мелком экране всё равно не разглядеть: волокна радужки, блик, спицы
 *      колёс, бегущий блеск нимба. Силуэт, крылья, взгляд и моргание
 *      остаются — это и есть образ.
 * Режим можно продавить руками: ANGEL.lo = true/false.                       */
function angelLo() {
  if (ANGEL.lo != null) return ANGEL.lo;
  var w = (typeof window !== 'undefined') ? (window.innerWidth || 1200) : 1200;
  var touch = (typeof navigator !== 'undefined') && (navigator.maxTouchPoints > 0);
  ANGEL.lo = (w < 900) || !!touch;
  return ANGEL.lo;
}

// Кэш градиентов: ключ строкой, сборка — колбэком. Ёмкость ограничена, иначе
// квантованные ключи со временем накапливаются в утечку.
ANGEL.gc = {}; ANGEL.gcN = 0;
function angelGrad(k, make) {
  var g = ANGEL.gc[k];
  if (g) return g;
  if (ANGEL.gcN > 400) { ANGEL.gc = {}; ANGEL.gcN = 0; }
  g = make(); ANGEL.gc[k] = g; ANGEL.gcN++;
  return g;
}
function angelQ(v, step) { return Math.round(v / step) * step; }

// Часы спрайта в секундах. Отдельные от игровых: анимация не должна зависеть
// ни от хода, ни от задержек сети — оно живёт, даже когда доска ждёт сервер.
function angelT() {
  return ((typeof performance !== 'undefined' ? performance.now() : Date.now()) - ANGEL.t0) / 1000;
}

// Доске: пока ангел в кадре, гоняем rAF. Без этого крылья замирали бы между
// действиями игрока — доска перерисовывается только по событию.
function angelWantsFrames() { return ANGEL.live > 0; }

// Вспышка на попадании. Урона у ангела нет, но игрок должен видеть, что его
// залп ДОШЁЛ и не значил ничего, — иначе доска читается как сломанная.
function angelHit(id) {
  ANGEL.hits[id || '_'] = angelT();
}

// Сервер считает попадания в pk.ang. Сравниваем с прошлым кадром — выросло,
// значит по нему только что стреляли.
function angelSyncHits(u) {
  if (!u || u.id == null) return;
  var n = (u.pk && +u.pk.ang) || 0;
  var was = ANGEL.seen[u.id];
  if (was != null && n > was) angelHit(u.id);
  ANGEL.seen[u.id] = n;
}

/* ── РАСКЛАДКА ГЛАЗ ─────────────────────────────────────────
 * Глаза раскиданы по двум кольцам и по телу. Раскладку считаем ОДИН раз и
 * держим: если гонять random() каждый кадр, глаза прыгают, и вместо ужаса
 * получается рябь. Каждому глазу даётся свой ритм моргания и своя фаза —
 * поэтому они никогда не моргают строем.                                    */
function angelEyes() {
  if (ANGEL.eyes) return ANGEL.eyes;
  var rnd = (function (s) {           // свой генератор: раскладка одна и та же
    return function () { s = (s * 1664525 + 1013904223) % 4294967296; return s / 4294967296; };
  })(20250819);
  var E = [];
  // Кольца пронумерованы ключом k, а не порядком в массиве: колёс стало три,
  // и порядок отрисовки (дальнее → ближнее) больше не совпадает с номером.
  // «И ободья их — высоки и страшны; ободья их у всех четырёх вокруг полны
  //  глаз» — глаз должно быть МНОГО, иначе колесо читается как обруч с бусами.
  var ring = function (k, n, r, w, szmin) {
    for (var i = 0; i < n; i++) {
      E.push({ ring: k, a: (i / n) * Math.PI * 2 + (k * 0.21), r: r, w: w,
               sz: szmin + rnd() * 0.05, blink: 2.0 + rnd() * 5.5, ph: rnd() * 10,
               // «мелкий» глаз рисуется только на крупном плане: на доске он
               // всё равно ушёл бы в штрих и только жрал бы кадр
               fine: (i % 2 === 1) });
    }
  };
  // РАЗМЕР ГЛАЗА. Крупный глаз на ободе читается бусиной, а ряд бусин — цепью:
  // ровно та беда, из-за которой первая версия выглядела ожерельем. Глаз должен
  // быть МЕЛЬЧЕ толщины обода и сидеть В нём — тогда колесо остаётся колесом, а
  // глаза его населяют. Поэтому их и много, и они мелкие.
  ring(0, 26, 1.00, 0.30, 0.052);   // внешнее колесо
  ring(1, 18, 0.62, 0.62, 0.058);   // внутреннее, идёт навстречу
  ring(3, 13, 0.80, 0.44, 0.054);   // третье, наклон поперёк первым двум
  // глаза на самом теле — те, что не двигаются вовсе
  for (var k = 0; k < 7; k++) {
    E.push({ ring: 2, a: (k / 7) * Math.PI * 2 + 0.4, r: 0.26,
             sz: 0.105 + rnd() * 0.035, blink: 3.0 + rnd() * 6.0, ph: rnd() * 10,
             fine: (k % 2 === 1) });
  }
  ANGEL.eyes = E;
  return E;
}

/* ── СТУПЕНЬ ПОДРОБНОСТИ ────────────────────────────────────
 * Один спрайт живёт на трёх экранах сразу: точка на карте галактики (R≈10),
 * борт на доске боя (R≈20–35) и крупный план в карточке (R≈60+). Рисовать
 * везде одно и то же неверно в обе стороны: на карте лишние слои сливаются в
 * грязь и жгут кадр, а на крупном плане тех же слоёв ПОЗОРНО МАЛО — ангел
 * Иезекииля это не «фигурка с крылышками и кружком», это машина из колёс,
 * зубьев, глаз, перьев, углей и молний. Поэтому подробность — функция от
 * размера, а бережливый режим только опускает потолок.
 *   0 — силуэт: колёса штрихом, глаза прорезями;
 *   1 — доска: полный набор слоёв, без мелочи;
 *   2 — богатый: зубья ободьев, стержни и бородки перьев, глаза на крыльях,
 *       угли в столбе, молнии между колёс;
 *   3 — крупный план: третье колесо, мелкие глаза, волокна радужки, блик,
 *       второй обод нимба и лучи.                                            */
// cap — ПОТОЛОК ступени от вызывающего. Ступень считалась только от радиуса, и
// это вышло боком карте галактики: чтобы ковчег не терялся среди флотов, карта
// просит R до 58 — то есть невольно заказывала ступень 3, САМУЮ тяжёлую, да ещё
// в оверлее, который перерисовывается целиком на каждый кадр панорамы. Радиус
// на карте говорит «сделай заметным», а не «сделай подробным»: это разные
// просьбы, и теперь их можно разделить (см. opt.detail в angelDrawCore).
function angelDetail(R, cap) {
  var lo = angelLo();
  var d;
  if (R < (lo ? 13 : 10)) d = 0;
  else if (lo) d = 1;               // телефону выше первой ступени не даём
  else if (R < 22) d = 1;
  else if (R < 40) d = 2;
  else d = 3;
  return (cap == null) ? d : Math.min(d, cap);
}

/* ── ГЕОМЕТРИЯ ГЛАЗА: SVG-путь, а не эллипсы ────────────────
 * ПОЧЕМУ ПЕРЕПИСАНО. Первая версия рисовала глаз как ctx.ellipse — круглую
 * плошку с точкой внутри. На доске это ещё сходило, а на карте превратилось
 * ровно в то, чем и было: россыпь жёлтых бусин, читаемых как смайлики.
 * Круг — не глаз. Глаз это МИНДАЛЬ с острыми углами по краям, и именно углы
 * дают взгляд; без них любая точка внутри круга остаётся точкой внутри круга.
 *
 * Поэтому форма задана путём SVG (те же кривые Безье, что в редакторе) и
 * собрана один раз в Path2D. Дальше её только двигают, вертят и масштабируют
 * матрицей — это и быстрее (нет пересборки контура на каждый глаз каждый кадр),
 * и честнее: одна геометрия на все размеры, от карты до крупного плана.
 *
 * ВТОРОЕ, ЧТО ЛЕЧИТ «БУСИНЫ»: разворот. Раньше все глаза стояли строго
 * горизонтально, из-за чего кольцо читалось как ожерелье. Теперь каждый глаз
 * развёрнут по касательной к своему колесу — колесо смотрит наружу целиком.  */
var ANGEL_EYE_D = 'M -1 0 C -0.55 -0.70 -0.20 -0.82 0 -0.82'
                + ' C 0.20 -0.82 0.55 -0.70 1 0'
                + ' C 0.55 0.70 0.20 0.82 0 0.82'
                + ' C -0.20 0.82 -0.55 0.70 -1 0 Z';
// Веко: та же миндалина, но «полная» — ею закрывают глаз сверху вниз.
var ANGEL_LID_D = 'M -1 0.06 C -0.55 -0.74 -0.20 -0.88 0 -0.88'
                + ' C 0.20 -0.88 0.55 -0.74 1 0.06'
                + ' C 0.55 -0.30 -0.55 -0.30 -1 0.06 Z';
var ANGEL_P = null;
function angelPaths() {
  if (!ANGEL_P && typeof Path2D === 'function') {
    ANGEL_P = { eye: new Path2D(ANGEL_EYE_D), lid: new Path2D(ANGEL_LID_D) };
  }
  return ANGEL_P;
}

/* ── ОДИН ГЛАЗ ──────────────────────────────────────────────
 * x, y — центр; rad — половина ширины; rot — разворот миндалины;
 * gaze — куда смотрит зрачок (в мировых радианах, НЕ в местных: весь смысл
 * в том, что развёрнутые по-разному глаза глядят в одну точку);
 * lid — 0 открыт, 1 закрыт.                                                  */
function angelEye(x, ex, ey, rad, gaze, lid, rot) {
  var P = angelPaths();
  // МЕЛКИЙ МАСШТАБ (карта). Ниже двух пикселей никакая форма не читается, и
  // попытка нарисовать там радужку с бликом даёт грязное пятно — то самое,
  // что выглядело бусиной. Рисуем штрих по касательной: издали это верно
  // читается как «прорезь», а не как «кружок».
  if (rad < (angelLo() ? 3.2 : 2.1) || !P) {
    if (lid > 0.6) return;
    x.save();
    x.translate(ex, ey); x.rotate(rot || 0);
    x.strokeStyle = 'rgba(255,236,180,' + (0.92 * (1 - lid)) + ')';
    x.lineWidth = Math.max(0.6, rad * 0.85);
    x.lineCap = 'round';
    x.beginPath(); x.moveTo(-rad, 0); x.lineTo(rad, 0); x.stroke();
    x.restore();
    return;
  }

  x.save();
  x.translate(ex, ey);
  x.rotate(rot || 0);
  x.scale(rad, rad);              // путь задан в единичных долях

  // склера
  x.fillStyle = 'rgba(250,244,224,0.97)';
  x.fill(P.eye);

  x.save();
  x.clip(P.eye);                  // всё нутро режем по миндалине

  // РАДУЖКА. Зрачок ведём в МЕСТНЫХ координатах: вычитаем разворот глаза из
  // мирового направления взгляда — иначе развёрнутые глаза косили бы каждый
  // в свою сторону, и вместо общего взгляда выходило бы стадо.
  var ga = (gaze || 0) - (rot || 0);
  var px = Math.cos(ga) * 0.34, py = Math.sin(ga) * 0.30;
  var ir = 0.52;
  // Градиент радужки живёт в ЕДИНИЧНЫХ координатах (путь уже отмасштабирован),
  // поэтому зависит только от направления взгляда. Квантуем его на 32 шага и
  // держим готовым, а разницу доводим сдвигом холста: раньше объект градиента
  // заводился на каждый глаз каждый кадр — под три десятка штук на пустом месте.
  var qa = angelQ(ga, 0.1963);
  var qx = Math.cos(qa) * 0.34, qy = Math.sin(qa) * 0.30;
  x.save(); x.translate(px - qx, py - qy);
  x.beginPath(); x.arc(qx, qy, ir, 0, 6.2832);
  x.fillStyle = angelGrad('ir' + qa.toFixed(2), function () {
    var g = x.createRadialGradient(qx, qy, 0.04, qx, qy, ir);
    g.addColorStop(0, 'rgba(255,222,128,1)');
    g.addColorStop(0.5, 'rgba(206,140,34,1)');
    g.addColorStop(1, 'rgba(70,38,8,1)');
    return g;
  });
  x.fill();
  x.restore();

  // Волокна радужки — то, что отличает глаз от кружка с градиентом. На телефоне
  // снимаем: 12 штрихов на глаз при 28 глазах — 336 штрихов в кадр ради узора
  // шириной в полпикселя, которого там физически не видно.
  if (rad >= 5.5) {
    x.strokeStyle = 'rgba(120,66,12,0.5)';
    x.lineWidth = 0.022;
    for (var f = 0; f < 12; f++) {
      var fa = f * 0.5236;
      x.beginPath();
      x.moveTo(px + Math.cos(fa) * ir * 0.42, py + Math.sin(fa) * ir * 0.42);
      x.lineTo(px + Math.cos(fa) * ir * 0.96, py + Math.sin(fa) * ir * 0.96);
      x.stroke();
    }
  }

  // зрачок — вертикальная щель, а не точка: круглый зрачок читается как
  // человеческий, а это не человек
  x.beginPath();
  x.ellipse(px, py, ir * 0.30, ir * 0.72, ga + Math.PI / 2, 0, 6.2832);
  x.fillStyle = 'rgba(6,4,2,1)'; x.fill();

  // блик — единственная холодная нота на всём тёплом (на телефоне не читается)
  if (rad >= 3.5) {
    x.beginPath();
    x.arc(px - ir * 0.30, py - ir * 0.34, ir * 0.17, 0, 6.2832);
    x.fillStyle = 'rgba(255,255,255,0.9)'; x.fill();
  }

  // ВЕКО. Не сплющивание миндалины (от него глаз «худеет», как закрывающийся
  // рот), а настоящая створка, которая ЕДЕТ сверху вниз внутри контура.
  if (lid > 0.001) {
    x.save();
    x.translate(0, -1.72 + lid * 1.72);
    x.fillStyle = 'rgba(214,176,104,0.99)';
    x.fill(P.lid);
    x.fillStyle = 'rgba(150,110,52,0.9)';       // складка на кромке века
    x.fillRect(-1.05, 0.02, 2.1, 0.07);
    x.restore();
  }
  x.restore();                    // снять клип

  // обвод последним, поверх века — контур глаза не исчезает, когда он закрыт
  x.lineWidth = 0.075;
  x.strokeStyle = 'rgba(132,96,36,0.95)';
  x.stroke(P.eye);
  x.restore();
}

/* ── ОДНО КРЫЛО ─────────────────────────────────────────────
 * Не «птичье крыло с пёрышками», а веер маховых перьев: три-четыре пера
 * разной длины из одной точки. Так оно читается даже на мелком зуме, где
 * настоящая детализация превратилась бы в кашу.                              */
function angelWing(x, R, side, spread, beat, alpha, D, gz) {
  var s = side;                    // +1 — правое, -1 — левое
  var base = spread + beat * 0.42;
  x.save();
  x.rotate(s * base);
  var n = D >= 2 ? 6 : (D >= 1 ? 4 : 3);   // маховых перьев в веере
  for (var i = 0; i < n; i++) {
    var f = i / (n - 1);
    var len = R * (2.15 - f * 0.72);
    var wid = R * (0.30 - f * 0.10);
    var curl = s * (0.30 + f * 0.55 + beat * 0.16);
    var tipY = s * curl * R * 0.5;
    x.beginPath();
    x.moveTo(0, 0);
    x.quadraticCurveTo(len * 0.45, s * wid * 2.1, len, tipY);
    x.quadraticCurveTo(len * 0.5, s * wid * 0.15, 0, 0);
    x.closePath();
    // Градиент пера зависит только от длины и прозрачности — квантуем оба и
    // берём готовый: 16 новых градиентов в кадр на борт превращаются в ноль.
    var ql = Math.max(1, angelQ(len, 2)), qal = angelQ(alpha, 0.05);
    x.fillStyle = angelGrad('w' + ql + '_' + qal.toFixed(2), function () {
      var g = x.createLinearGradient(0, 0, ql, 0);
      g.addColorStop(0, 'rgba(255,250,232,' + (0.90 * qal) + ')');
      g.addColorStop(0.5, 'rgba(238,214,150,' + (0.62 * qal) + ')');
      g.addColorStop(1, 'rgba(196,140,44,' + (0.05 * qal) + ')');
      return g;
    });
    x.fill();
    x.strokeStyle = 'rgba(255,246,214,' + (0.30 * alpha) + ')';
    x.lineWidth = Math.max(0.4, R * 0.018);
    x.stroke();

    // ПЕРО ВБЛИЗИ. Заливка с обводкой — это лопасть, а не перо. Перо читается
    // стержнем и бородками: стержень идёт от основания к кончику по той же
    // кривой, бородки отходят от него назад под острым углом. Считаем по той
    // же квадратичной кривой (точки на ней), поэтому рисунок не «наклеен», а
    // лежит на форме и живёт вместе с ней при взмахе.
    if (D >= 2) {
      var cxq = len * 0.45, cyq = s * wid * 1.05;   // средняя линия пера
      var at = function (u) {
        var m = 1 - u;
        return [m * m * 0 + 2 * m * u * cxq + u * u * len,
                m * m * 0 + 2 * m * u * cyq + u * u * tipY];
      };
      x.lineWidth = Math.max(0.35, R * 0.012);
      x.strokeStyle = 'rgba(255,252,238,' + (0.55 * alpha) + ')';
      x.beginPath();
      var p0 = at(0); x.moveTo(p0[0], p0[1]);
      for (var u = 0.1; u <= 1.001; u += 0.1) { var pu = at(u); x.lineTo(pu[0], pu[1]); }
      x.stroke();
      x.lineWidth = Math.max(0.25, R * 0.006);
      x.strokeStyle = 'rgba(246,228,180,' + (0.20 * alpha) + ')';
      x.beginPath();
      for (var v = 0.18; v < 0.98; v += 0.075) {
        var pv = at(v), pw = at(Math.min(1, v + 0.06));
        var dx = pw[0] - pv[0], dy = pw[1] - pv[1];
        var dl = Math.hypot(dx, dy) || 1;
        // бородка: назад по стержню и вбок, длина падает к кончику
        var bl = R * 0.15 * (1 - v * 0.55);
        x.moveTo(pv[0], pv[1]);
        x.lineTo(pv[0] - dx / dl * bl * 0.35 + (-dy / dl) * bl * s,
                 pv[1] - dy / dl * bl * 0.35 + (dx / dl) * bl * s);
      }
      x.stroke();
    }
  }

  // «ВСЁ ТЕЛО ИХ… И КРЫЛЬЯ ИХ ПОЛНЫ БЫЛИ ОЧЕЙ». Глаза на крыле — то, чего
  // спрайту не хватало больше всего: без них крылья остаются птичьими, а с
  // ними становится ясно, что смотрит не «голова», а существо целиком.
  if (D >= 2 && gz != null) {
    // Сидят на СЕРЕДИНЕ размаха и дальше: у основания все шесть крыльев
    // сходятся в одну точку, и посаженные там глаза сбивались с глазами колёс
    // в одну гроздь — вместо «крылья полны очей» выходила виноградина.
    for (var e = 0; e < 2; e++) {
      var q = 0.62 + e * 0.30;
      var ex = R * 1.05 * q, ey = s * R * (0.34 + q * 0.30);
      var ph = ((angelT() * 0.9 + e * 2.3 + side) % 4.1) / 4.1;
      var lid = ph > 0.9 ? Math.sin((ph - 0.9) / 0.1 * Math.PI) : 0;
      angelEye(x, ex, ey, R * 0.068, gz - s * base, lid, s * base + Math.atan2(ey, ex));
    }
  }
  x.restore();
}

/* ── ЗАСЛОНКА («ЧЁРНЫЙ КВАДРАТ») ────────────────────────────
 * ЗАЧЕМ. В спрайте с самого начала записано «лика нет, внутри столб света и
 * пустота». Замысел верный, но НЕ ЧИТАЕМЫЙ: пустое место зритель не отличает
 * от недорисованного — «лица нет» и «лицо не нарисовали» выглядят одинаково.
 * Квадрат говорит третье и худшее: лицо ЕСТЬ, и его от тебя закрыли. Пустота
 * ничего не обещает, заслонка обещает то, чего не покажут.
 *
 * ГДЕ В СЛОЯХ. Последним слоем, поверх всего, кроме вспышки попадания. Заход
 * убрать её под кольца (чтобы не прятала ювелирку) забракован на глаз: между
 * ободьями она тонет и читается случайной тенью, а не запретом. Заслонка и
 * ДОЛЖНА закрывать самое красивое — то, что закрывает лишь не жалкое, никакой
 * заслонкой не является.
 *
 * ПОЧЕМУ ПО ОСЯМ ЭКРАНА, А НЕ СПРАЙТА. Это и есть весь приём. Колёса вертятся,
 * связка качается, крылья бьют — а квадрат стоит строго по горизонтали и не
 * участвует ни в одном движении. Деталь существа так себя вести не может;
 * значит, он не деталь существа, а НАЛОЖЕН НА ИЗОБРАЖЕНИЕ существа — кем-то,
 * кто смотрит на ту же картинку, что и игрок, и решил, что этого ему нельзя.
 * Технически это бесплатно: к моменту вызова холст только сдвинут в центр
 * борта, все повороты живут внутри save/restore, поэтому здесь оси уже
 * экранные. ⚠️ Если когда-нибудь доска начнёт ВРАЩАТЬ холст перед вызовом
 * angelDraw — заслонку придётся выставлять через setTransform, иначе приём
 * сломается молча.
 *
 * ПОЧЕМУ КВАДРАТ НЕ ПРОСТО ЗАЛИТЬ ЧЁРНЫМ. Доска чёрная. Чёрное на чёрном —
 * это не квадрат, это дырка, которой не видно. Поэтому за ним подложено
 * свечение (силуэт вырезается из света), а по кромке идёт тонкий холодный
 * контур — единственная холодная линия на всём тёплом спрайте.
 *
 * ПЕЧАТИ. Чем их меньше, тем хуже держится заслонка: дрожь сильнее и по ней
 * чаще идёт разрыв строки. Но ОТКРЫТЬ она не может никогда — под разрывом
 * ровно такая же чернота. Показать там что-нибудь значило бы ответить на
 * вопрос, ради которого весь приём и заведён.                                */
function angelVeil(x, R, t, vigor, seals, D, hitK) {
  var w = R * 0.66, h = R * 0.62;
  var cyv = -R * 0.34;                       // там, где у существа была бы голова
  // Дрожь: заслонка ведёт цель, а цель шевелится. Умирающий ангел ведёт хуже.
  var slip = 1 - seals;
  var jx = Math.sin(t * 3.1) * R * (0.012 + slip * 0.045)
         + Math.sin(t * 11.3) * R * slip * 0.03;
  var jy = Math.cos(t * 2.3) * R * (0.010 + slip * 0.035);
  // Попадание сбивает наводку заслонки сильнее, чем что-либо ещё на спрайте.
  if (hitK > 0) { jx += (Math.random() - 0.5) * R * 0.22 * hitK; }

  x.save();
  x.translate(jx, jy);

  // Подсветка под квадратом: сверху он местами ложится на пустой космос, а
  // чёрное на чёрном — это не квадрат, это ничто. Силуэт вырезаем из света.
  var qh = Math.max(2, angelQ(w * 1.9, 2));
  x.beginPath(); x.arc(0, cyv, qh, 0, Math.PI * 2);
  x.fillStyle = angelGrad('vh' + qh + '_' + angelQ(vigor, 0.1).toFixed(1), function () {
    var g = x.createRadialGradient(0, cyv, qh * 0.25, 0, cyv, qh);
    g.addColorStop(0, 'rgba(255,250,232,' + (0.42 * vigor) + ')');
    g.addColorStop(1, 'rgba(255,240,200,0)');
    return g;
  });
  x.fill();

  // САМ КВАДРАТ. Настоящий чёрный, без прозрачности: это не тень и не дымка,
  // это вырезанное место.
  x.fillStyle = '#000';
  x.fillRect(-w / 2, cyv - h / 2, w, h);

  // РАЗРЫВ СТРОКИ. Полоса съезжает вбок — как сбитая развёртка. Под ней та же
  // чернота: заслонка не приоткрывается, она только хуже держится.
  if (D >= 1) {
    var period = 1.6 - seals * 0.7;
    var into = t % period;
    if (into < 0.09 + slip * 0.09) {
      var band = h * (0.12 + slip * 0.16);
      var by = cyv - h / 2 + ((t * 97) % 1) * (h - band);
      var off = R * (0.06 + slip * 0.10);
      x.fillRect(-w / 2 + off, by, w, band);
      x.fillStyle = 'rgba(210,236,255,' + (0.30 + slip * 0.35) + ')';
      x.fillRect(-w / 2 + off, by, w, Math.max(0.6, R * 0.008));
      x.fillStyle = '#000';
    }
  }

  // КРОМКА — единственная холодная линия на всём тёплом спрайте.
  x.strokeStyle = 'rgba(196,224,255,' + (0.34 + 0.5 * hitK) + ')';
  x.lineWidth = Math.max(0.5, R * 0.012);
  x.strokeRect(-w / 2, cyv - h / 2, w, h);

  // УГОЛКИ. Вблизи видно, что заслонка ПРИСТАВЛЕНА: у неё есть углы рамки,
  // как у кадра видоискателя, который ведёт цель.
  if (D >= 3) {
    var cl = R * 0.13, m = R * 0.05;
    x.strokeStyle = 'rgba(196,224,255,0.5)';
    x.lineWidth = Math.max(0.5, R * 0.010);
    x.beginPath();
    [[-1, -1], [1, -1], [-1, 1], [1, 1]].forEach(function (c) {
      var px2 = c[0] * (w / 2 + m), py2 = cyv + c[1] * (h / 2 + m);
      x.moveTo(px2 - c[0] * cl, py2); x.lineTo(px2, py2); x.lineTo(px2, py2 - c[1] * cl);
    });
    x.stroke();
  }
  x.restore();
}

/* ── ГЛАВНОЕ: НАРИСОВАТЬ ПРЕСТОЛ ────────────────────────────
 * opt: { cx, cy, R, alpha, tone (rgb-строка), gaze (радианы), id, seals (0..1) }
 *
 * ПОРЯДОК СЛОЁВ снизу вверх: свечение → нижние крылья → средние крылья →
 * колёса с глазами → молнии → тело с углями → верхние крылья → нимб →
 * ЗАСЛОНКА → вспышка. Крылья РАЗНЕСЕНЫ по слоям нарочно: так тело оказывается
 * «внутри» крыльев, а не поверх них.
 *
 * ЧТО ДОБАВЛЕНО ПРОТИВ ПЕРВОЙ ВЕРСИИ И ЗАЧЕМ. Первый заход давал верные
 * ПРИЗНАКИ ангела (колёса, глаза, шесть крыл, нимб), но в каждом признаке по
 * одной линии — и вместе они читались как схема, а не как существо. У Иезекииля
 * подробность и есть содержание: обод не линия, а полоса, «высокая и страшная»,
 * с зубьями; глаз не десяток, а «полны очей вокруг»; между колёс ходит огонь и
 * из огня выходит молния; колёс не два, а колесо в колесе. Всё это добавлено
 * ступенями (см. angelDetail): на карте — прежний силуэт, на доске — плотнее,
 * на крупном плане — полностью. Телефон выше первой ступени не поднимается,
 * поэтому «детальнее» не значит «тяжелее там, где тяжело».                    */
function angelDraw(x, opt) {
  // ПРЕДОХРАНИТЕЛЬ. Спрайт рисуется в чужом кадре: на доске боя, на карте и в
  // 3D — в цикле, который сам себя перезапускает, пока ангел на поле. Значит
  // ЛЮБАЯ ошибка здесь падает не один раз, а шестьдесят раз в секунду, и всё,
  // что должно было рисоваться ПОСЛЕ ангела, не рисуется вовсе: доска чернеет,
  // процессор в полке, а в консоли одна и та же строка бесконечной лентой.
  // Так и случилось при перестановке слоёв (тело поехало раньше колёс и
  // забрало с собой раскладку глаз). Поэтому: сорвался — жалуемся ОДИН раз и
  // больше не пытаемся. Пусть борт останется без спрайта, чем доска без боя.
  if (ANGEL.dead) return;
  try {
    angelDrawCore(x, opt);
  } catch (e) {
    ANGEL.dead = true;
    if (typeof console !== 'undefined') console.error('◈ Престол: спрайт снят с отрисовки', e);
  }
}
function angelDrawCore(x, opt) {
  // opt.bake — рисуем не в кадр, а в офскрин-заготовку: счётчик «ангел в кадре»
  // трогать нельзя, иначе доска будет вечно гнать rAF из-за одной выпечки.
  if (!opt.bake) ANGEL.live++;
  var cx = opt.cx, cy = opt.cy, R = opt.R || 20;
  var A = opt.alpha == null ? 1 : opt.alpha;
  var tone = opt.tone || '255,220,140';
  // Фазу можно ЗАДАТЬ (opt.t) — на этом стоит выпечка: у запечённого кадра
  // время не идёт, и поза должна быть одной и той же при каждой перепечке.
  var t = opt.t == null ? angelT() : opt.t;
  var gaze = opt.gaze == null ? -Math.PI / 2 : opt.gaze;
  var seals = opt.seals == null ? 1 : Math.max(0, Math.min(1, opt.seals));
  // ◈ СТРАЖА (opt.guard). Не отдельный рисунок, а ЭТОТ, снятый на ступень вниз:
  // подобия делал он сам и делал по себе, значит и облик у них его — только
  // беднее. Что снимаем: третье колесо (гироскоп схлопывается в два обода),
  // верхнюю пару крыл (лица они не закрывают — им нечего закрывать), нимб и
  // огонь между колёс. Что оставляем: глаза, ободья, маховые крылья, свечение.
  // ⚠️ Подробность режем потолком, а не радиусом: на доске стража стоит рядом с
  // ковчегом, и разница должна читаться в ОБЛИКЕ, а не в том, что «мельче».
  var gd = !!opt.guard;
  var D = angelDetail(R, gd ? Math.min(1, opt.detail == null ? 1 : opt.detail) : opt.detail);
  // Раскладку глаз берём В НАЧАЛЕ: ею пользуются и тело, и все три колеса, а
  // тело теперь рисуется РАНЬШЕ колёс — между ними легла заслонка.
  var E = angelEyes();
  // Печати ниже — свет тусклее и дыхание чаще: издыхающий ангел ВИДНО,
  // и это единственная подсказка галактике, что кампания работает.
  var vigor = (0.45 + seals * 0.55) * (gd ? 0.72 : 1);
  var breath = Math.sin(t * (1.1 + (1 - seals) * 1.7));

  x.save();
  x.globalAlpha = A;
  x.translate(cx, cy);

  // 1) ДАЛЬНЕЕ СВЕЧЕНИЕ — единственное место, где виден цвет стороны.
  // Свечение «дышит», но квантованного шага в 2 px глазу хватает — иначе на
  // каждый кадр заводился новый радиальный градиент во всю ширину борта.
  var halo = Math.max(2, angelQ(R * (gd ? 1.9 : 2.9) * (1 + breath * 0.04), 2));
  var qv = angelQ(vigor, 0.1);
  x.beginPath(); x.arc(0, 0, halo, 0, Math.PI * 2);
  x.fillStyle = angelGrad('h' + halo + '_' + qv.toFixed(1) + '_' + tone, function () {
    var g = x.createRadialGradient(0, 0, halo * 0.07, 0, 0, halo);
    g.addColorStop(0, 'rgba(255,244,206,' + (0.30 * qv) + ')');
    g.addColorStop(0.45, 'rgba(' + tone + ',' + (0.13 * qv) + ')');
    g.addColorStop(1, 'rgba(' + tone + ',0)');
    return g;
  });
  x.fill();

  // 2) НИЖНЯЯ ПАРА КРЫЛ — «ими закрывал ноги». Бьют медленно и глубоко.
  var beatLo = Math.sin(t * 1.5) * 0.5;
  var rotLo = Math.PI * 0.62;
  x.save();
  x.rotate(rotLo);
  angelWing(x, R, +1, 0.30, beatLo, 0.55 * vigor, D, gaze - rotLo);
  angelWing(x, R, -1, 0.30, beatLo, 0.55 * vigor, D, gaze - rotLo);
  x.restore();

  // 3) СРЕДНЯЯ ПАРА — маховая, самая быстрая: ею оно и движется
  var beatMid = Math.sin(t * 2.7 + 1.2) * 0.72;
  angelWing(x, R, +1, 0.02, beatMid, 0.95 * vigor, D, gaze);
  angelWing(x, R, -1, 0.02, beatMid, 0.95 * vigor, D, gaze);

  // 4) ОФАНИМ — колёса навстречу друг другу. Наклон у каждого свой, поэтому в
  //    любой момент видно все, и ни одно не сливается с плоскостью доски.
  //    Третье появляется только на крупном плане: «колесо в колесе» на доске
  //    превращается в кашу, а вблизи без него плоско.
  // НАКЛОНЫ НЕ СЛУЧАЙНЫЕ. В первой версии они были взяты на глаз (0.34 / 1.05),
  // и три обода под произвольными углами читались как ворох колец. «Колесо
  // в колесе» у Иезекииля — это ровно гироскоп: два обода одного размера,
  // поставленные ПОПЕРЁК друг друга, и третий, меньший, внутри. Такая связка
  // узнаётся с первого взгляда и не разваливается при вращении, потому что
  // углы между ободами постоянны, а качается связка целиком (wob).
  var wob = Math.sin(t * 0.37) * 0.22;
  var rings = [
    { k: 0, rot:  t * 0.42, tilt: wob,                 rad: R * 1.55, w: 0.30 },
    { k: 3, rot:  t * 0.31, tilt: wob + Math.PI / 2,   rad: R * 1.48, w: 0.30, only: 2 },
    { k: 1, rot: -t * 0.66, tilt: wob + Math.PI / 4,   rad: R * 0.92, w: 0.58 },
  ];
  rings.forEach(function (rg) {
    if (rg.only && D < rg.only) return;
    if (gd && rg.k === 1) return;      // у стражи колеса в колесе нет
    x.save();
    x.rotate(rg.tilt);

    // ОБОД — ЗАЛИТАЯ ПОЛОСА, А НЕ ЛИНИЯ. Три обводки друг за другом давали
    // ровно то, что и должны были: три тонкие линии, которые в гуще перьев и
    // глаз просто теряются. «Ободья их высоки и страшны» — значит у обода есть
    // ШИРИНА и он непрозрачен: чертим кольцо одним контуром (внешний эллипс
    // плюс внутренний в обратную сторону, дырка по evenodd) и ЗАЛИВАЕМ. Только
    // после этого колесо перестаёт быть проволочным и начинает загораживать
    // собой то, что за ним, — а это и есть объём.
    var inR = rg.rad * 0.760;   // обод шире глаза — иначе глаз висит НА нём, а не В нём
    x.beginPath();
    x.ellipse(0, 0, rg.rad, rg.rad * rg.w, 0, 0, Math.PI * 2);
    x.ellipse(0, 0, inR, inR * rg.w, 0, Math.PI * 2, 0, true);
    var qw = angelQ(rg.rad, 3);
    x.fillStyle = angelGrad('rim' + qw + '_' + qv.toFixed(1), function () {
      var g = x.createLinearGradient(-qw, 0, qw, 0);
      g.addColorStop(0, 'rgba(120,92,40,' + (0.85 * qv) + ')');
      g.addColorStop(0.32, 'rgba(242,214,146,' + (0.95 * qv) + ')');
      g.addColorStop(0.55, 'rgba(255,244,206,' + (0.98 * qv) + ')');
      g.addColorStop(0.78, 'rgba(206,166,86,' + (0.92 * qv) + ')');
      g.addColorStop(1, 'rgba(96,72,30,' + (0.85 * qv) + ')');
      return g;
    });
    x.fill('evenodd');
    x.strokeStyle = 'rgba(74,52,18,' + (0.75 * vigor) + ')';   // кромка полосы
    x.lineWidth = Math.max(0.5, R * 0.016);
    x.stroke();

    // ЗУБЬЯ. Насечка ПО полосе (тёмные штрихи в толщине обода), а не спицы
    // поперёк пустоты: именно она показывает, что колесо вертится, — гладкое
    // кольцо вращается неотличимо от неподвижного.
    var teeth = D >= 2 ? 34 : (D >= 1 ? 16 : 0);
    if (teeth) {
      x.save();
      x.beginPath();
      x.ellipse(0, 0, rg.rad, rg.rad * rg.w, 0, 0, Math.PI * 2);
      x.ellipse(0, 0, inR, inR * rg.w, 0, Math.PI * 2, 0, true);
      x.clip('evenodd');
      x.strokeStyle = 'rgba(58,40,14,' + (0.55 * vigor) + ')';
      x.lineWidth = Math.max(0.5, R * 0.017);
      x.beginPath();
      for (var z = 0; z < teeth; z++) {
        var za = rg.rot * 1.6 + z * Math.PI * 2 / teeth;
        x.moveTo(Math.cos(za) * inR * 0.94, Math.sin(za) * inR * rg.w * 0.94);
        x.lineTo(Math.cos(za) * rg.rad * 1.06, Math.sin(za) * rg.rad * rg.w * 1.06);
      }
      x.stroke();
      x.restore();
    }
    // Спицы: без них колесо читается как просто обод. На телефоне снимаем —
    // при прозрачности 0.13 они там не видны вовсе, а это 16 штрихов в кадр.
    if (D >= 1) {
      x.strokeStyle = 'rgba(214,178,104,' + (0.10 * vigor) + ')';
      x.lineWidth = Math.max(0.35, R * 0.014);
      x.beginPath();
      for (var sp = 0; sp < 8; sp++) {
        var sa = rg.rot + sp * Math.PI / 4;
        x.moveTo(Math.cos(sa) * rg.rad * 0.30, Math.sin(sa) * rg.rad * rg.w * 0.30);
        x.lineTo(Math.cos(sa) * rg.rad, Math.sin(sa) * rg.rad * rg.w);
      }
      x.stroke();
    }
    x.restore();

    // ГЛАЗА ЭТОГО КОЛЕСА. Сидят В ПОЛОСЕ обода (радиус между внутренним и
    // внешним кругом), а не поверх линии: иначе они висят рядом с колесом,
    // а не принадлежат ему.
    var seat = (rg.rad + inR) / 2;
    E.forEach(function (e) {
      if (e.ring !== rg.k) return;
      if (e.fine && D < 3) return;          // мелочь только на крупном плане
      var a = e.a + rg.rot;
      var ex = Math.cos(a) * seat, ey = Math.sin(a) * seat * rg.w;
      var rot = rg.tilt;
      var px = ex * Math.cos(rot) - ey * Math.sin(rot);
      var py = ex * Math.sin(rot) + ey * Math.cos(rot);
      // Моргание: провал занимает 7% периода, но САМ по себе плавный — резкий
      // щелчок читается как подмигивание, а оно не подмигивает.
      var ph = ((t + e.ph) % e.blink) / e.blink;
      var lid = ph > 0.93 ? Math.sin((ph - 0.93) / 0.07 * Math.PI) : 0;
      // разворот по касательной к колесу (см. комментарий у ANGEL_EYE_D)
      angelEye(x, px, py, R * e.sz, gaze, lid, Math.atan2(py, px) + Math.PI / 2);
    });
  });

  // 5) ОГОНЬ МЕЖДУ КОЛЁС. «Подобие животных было как вид горящих углей, как вид
  //    лампад… и из огня выходила молния». Это единственное движение, которое
  //    происходит РЫВКОМ: всё остальное у него плавно, и на ровном плавном фоне
  //    рывок читается как чужая воля, а не как анимация.
  if (D >= 2 && !gd) {
    var bolt = Math.floor(t / 1.9);               // номер вспышки
    var into = t - bolt * 1.9;
    if (into < 0.16) {
      var bk = 1 - into / 0.16;
      var hs = (bolt * 2654435761) % 4294967296;
      var hr = function () { hs = (hs * 1664525 + 1013904223) % 4294967296; return hs / 4294967296; };
      x.save();
      x.globalCompositeOperation = 'lighter';
      x.strokeStyle = 'rgba(214,238,255,' + (0.85 * bk * vigor) + ')';
      x.lineWidth = Math.max(0.6, R * 0.035);
      x.lineJoin = 'round';
      for (var bz = 0; bz < 2; bz++) {
        var a0 = hr() * 6.2832, a1 = a0 + 1.6 + hr() * 3.0;
        var x0 = Math.cos(a0) * R * 1.45, y0 = Math.sin(a0) * R * 0.5;
        var x1 = Math.cos(a1) * R * 1.45, y1 = Math.sin(a1) * R * 0.5;
        x.beginPath(); x.moveTo(x0, y0);
        for (var seg = 1; seg < 5; seg++) {
          var u2 = seg / 5;
          x.lineTo(x0 + (x1 - x0) * u2 + (hr() - 0.5) * R * 0.55,
                   y0 + (y1 - y0) * u2 + (hr() - 0.5) * R * 0.55);
        }
        x.lineTo(x1, y1); x.stroke();
      }
      x.restore();
    }
  }

  // 6) ТЕЛО — столб света, лика нет
  var qr = Math.max(1, angelQ(R, 1));
  x.beginPath();
  x.ellipse(0, 0, R * 0.40, R * 1.15, 0, 0, Math.PI * 2);
  x.fillStyle = angelGrad('b' + qr + '_' + qv.toFixed(1), function () {
    var g = x.createLinearGradient(0, -qr * 1.15, 0, qr * 1.15);
    g.addColorStop(0, 'rgba(255,252,238,0)');
    g.addColorStop(0.35, 'rgba(255,250,232,' + (0.88 * qv) + ')');
    g.addColorStop(0.65, 'rgba(248,228,176,' + (0.80 * qv) + ')');
    g.addColorStop(1, 'rgba(255,252,238,0)');
    return g;
  });
  x.fill();

  // УГЛИ. «Огонь ходил между животными, и от огня исходило сияние». Столб без
  // них — ровная засветка, то есть пустое место в самой середине спрайта.
  // Угли идут ВВЕРХ и гаснут: этим столб получает направление и перестаёт быть
  // симметричной кляксой.
  if (D >= 2) {
    var emb = D >= 3 ? 16 : 9;
    x.save();
    x.globalCompositeOperation = 'lighter';
    for (var m = 0; m < emb; m++) {
      var pe = ((t * 0.55 + m * 0.137) % 1);
      var ey2 = R * 1.05 - pe * R * 2.1;
      var ex2 = Math.sin(m * 2.4 + t * 1.6) * R * 0.26 * (1 - pe * 0.35);
      var ea = Math.sin(pe * Math.PI) * 0.85 * vigor;
      var er = R * (0.030 + (m % 3) * 0.013);
      x.beginPath(); x.arc(ex2, ey2, er, 0, 6.2832);
      x.fillStyle = 'rgba(255,' + (196 + (m % 4) * 12) + ',120,' + ea.toFixed(3) + ')';
      x.fill();
    }
    x.restore();
  }

  // глаза на теле — неподвижные, самые крупные
  E.forEach(function (e) {
    if (e.ring !== 2) return;
    if (e.fine && D < 2) return;
    var ex = Math.cos(e.a) * R * e.r * 1.5, ey = Math.sin(e.a) * R * e.r * 2.4;
    var ph = ((t + e.ph) % e.blink) / e.blink;
    var lid = ph > 0.94 ? Math.sin((ph - 0.94) / 0.06 * Math.PI) : 0;
    // глаза тела стоят вертикально: тело — столб, и они читаются вдоль него
    angelEye(x, ex, ey, R * e.sz, gaze, lid, Math.PI / 2);
  });

  // 7) ВЕРХНЯЯ ПАРА КРЫЛ — «ими закрывал лице». Поверх тела, потому и закрывал.
  var beatHi = Math.sin(t * 2.0 + 2.6) * 0.44;
  var rotHi = -Math.PI * 0.58;
  if (!gd) {
    x.save();
    x.rotate(rotHi);
    angelWing(x, R, +1, 0.26, beatHi, 0.78 * vigor, D, gaze - rotHi);
    angelWing(x, R, -1, 0.26, beatHi, 0.78 * vigor, D, gaze - rotHi);
    x.restore();
  }

  // 8) НИМБ — наклонный обод с бегущим блеском. Не круг над головой:
  //    круг над головой читается как иконка, а не как объект.
  x.save();
  x.rotate(-0.28);
  if (gd) { x.restore(); } else {
  var nr = R * 1.28, nw = 0.26, ny = -R * 0.92;
  x.beginPath();
  x.ellipse(0, ny, nr, nr * nw, 0, 0, Math.PI * 2);
  x.strokeStyle = 'rgba(255,236,176,' + (0.85 * vigor) + ')';
  x.lineWidth = Math.max(1, R * 0.085);
  x.stroke();
  x.strokeStyle = 'rgba(255,255,240,' + (0.55 * vigor) + ')';
  x.lineWidth = Math.max(0.5, R * 0.03);
  x.stroke();
  // Вблизи один обод пустоват: добавляем второй, встречного наклона, и частые
  // лучи между ними — венец, а не кольцо.
  if (D >= 3) {
    x.strokeStyle = 'rgba(255,244,206,' + (0.34 * vigor) + ')';
    x.lineWidth = Math.max(0.5, R * 0.022);
    x.beginPath(); x.ellipse(0, ny, nr * 0.82, nr * 0.82 * (nw + 0.34), 0, 0, Math.PI * 2);
    x.stroke();
    x.strokeStyle = 'rgba(255,248,222,' + (0.24 * vigor) + ')';
    x.lineWidth = Math.max(0.35, R * 0.011);
    x.beginPath();
    for (var ry = 0; ry < 28; ry++) {
      var ra = t * 0.5 + ry * Math.PI * 2 / 28;
      x.moveTo(Math.cos(ra) * nr * 0.86, ny + Math.sin(ra) * nr * nw * 0.86);
      x.lineTo(Math.cos(ra) * nr * 1.10, ny + Math.sin(ra) * nr * nw * 1.10);
    }
    x.stroke();
  }
  // Блеск бежит по ободу. Он в движущейся точке, кэшировать нечего — поэтому
  // в бережливом режиме снимается первым.
  if (D >= 1) {
    var sa2 = (t * 1.35) % (Math.PI * 2);
    var sx = Math.cos(sa2) * nr, sy = ny + Math.sin(sa2) * nr * nw;
    var sg = x.createRadialGradient(sx, sy, 0, sx, sy, R * 0.42);
    sg.addColorStop(0, 'rgba(255,255,245,' + (0.9 * vigor) + ')');
    sg.addColorStop(1, 'rgba(255,255,245,0)');
    x.beginPath(); x.arc(sx, sy, R * 0.42, 0, Math.PI * 2);
    x.fillStyle = sg; x.fill();
  }
  x.restore();
  }

  // 9) ЗАСЛОНКА. Поверх ВСЕГО, кроме вспышки. Пробовали убрать её под кольца,
  //    чтобы не закрывала ювелирку, — стало хуже: заслонка утонула между
  //    ободьями и читалась случайной тенью, а не запретом. Она и должна
  //    закрывать красивое: в этом её работа. Что закрывает лишь то, что не
  //    жалко, — не заслонка.
  //    закрывала собой всё разом: и глаза колёс, и перья, и нимб. Смысл
  //    заслонки не в том, чтобы прятать спрайт, а в том, чтобы прятать ЛИК, —
  //    поэтому она легла прямо на столб света, а колёса, верхние крылья и
  //    нимб идут ПОВЕРХ неё. Заодно это читается вернее: не наклейка сверху,
  //    а слом внутри самого существа, вокруг которого всё продолжает вертеться.
  //    изображении борта, а значит закрывает и крылья, и нимб.
  var hitAt = ANGEL.hits[opt.id || '_'];
  var hitK = 0;
  if (hitAt != null) {
    var hdt = t - hitAt;
    if (hdt < 0.55) hitK = 1 - hdt / 0.55; else delete ANGEL.hits[opt.id || '_'];
  }
  if (D >= 1) angelVeil(x, R, t, vigor, seals, D, hitK);

  // 10) ВСПЫШКА ПОПАДАНИЯ — «ударили, и ничего не произошло»
  if (hitK > 0) {
    {
      var k = hitK;
      x.save();
      x.globalCompositeOperation = 'lighter';
      x.beginPath();
      x.arc(0, 0, R * (1.5 + (1 - k) * 2.2), 0, Math.PI * 2);
      x.strokeStyle = 'rgba(255,248,220,' + (0.75 * k) + ')';
      x.lineWidth = Math.max(1, R * 0.16 * k);
      x.stroke();
      x.restore();
    }
  }

  x.restore();
}

/* ── ПОЛОСА ПЕЧАТЕЙ ─────────────────────────────────────────
 * Вместо полоски корпуса: корпус у ангела бессмысленен (урона нет), а печати —
 * единственное, что о нём вообще можно знать. Делений ровно столько, сколько
 * снарядов Длани примерно осталось: игрок должен считать залпы, а не проценты. */
function angelSealBar(x, cx, cy, w, seals) {
  var f = Math.max(0, Math.min(1, seals == null ? 1 : seals));
  var n = 10, gap = w * 0.012, cw = (w - gap * (n - 1)) / n;
  x.save();
  for (var i = 0; i < n; i++) {
    var bx = cx - w / 2 + i * (cw + gap);
    var on = (i + 1) / n <= f + 1e-6;
    x.fillStyle = on
      ? (f > 0.35 ? 'rgba(255,226,150,0.95)' : 'rgba(255,120,90,0.95)')
      : 'rgba(255,255,255,0.10)';
    x.fillRect(bx, cy, cw, 3);
  }
  x.restore();
}

